<b>受访者6。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;：公务员，女，1980后，浙江杭州人</b> 

<p><b>请谈谈你目前的现状。</b>
<br>我是&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;道路运输管理局的一个秘书。毕业后考研究生，没考上。以前的设想肯定不是这样的，以前想到高校去当老师或者想办法出国，反正是没有想过自己会在一个党政机关这类的单位里过，完全没有想过。我工作五年了，应该说习惯了，至少会让你单位里的人认同你。我对现在的生活应该还算满意，还可以吧。我刚跟我的男朋友算是结婚了吧，不过还没领证。因为有了他，我觉得生活的中心更多地偏向于两个人的世界，养养狗什么，工作就是为了谋生了，现在可以过把工作和自己的生活分得比较清楚的生活。

<p><b>你怎么看待爱情？</b>
<br>爱情可能在不同的年龄段或者是在不同的状态下面貌是不一样的。我以前很喜欢去暗恋别人。有时候暗恋别人的确很美好，可以把别人无限地局限于一种很好的状态，但是却很不踏实。后来我就发现我在真正谈恋爱的时候不知道怎么跟一个人长期地相处，我也不知道感情进行到哪一步的时候，我可以做什么样的事情不会让对方觉得我很过分，我似乎什么都不知道。

<p><b>从小到大对你影响比较大的童话是什么？</b>
<br>安徒生的《海的女儿》，就是觉得很感动。我记得好像是我小学到一个同学家的时候借了这本书在他家看，本来想看一会儿就走，结果看完了才走，然后哭得稀里哗啦的。我就是觉得非常非常感动。可能这酿成我后来的暗恋情结。

<p><b>现在什么让你感到最焦虑？</b>
<br>我现在最焦虑的原因就是工作。我已经当了五年秘书了，来之前正好做完了我们半年的总结，很抓狂，要在不同的标题和内容梳理上下功夫，每次都要想出不一样的标题，同样一个东西切割成不同的，每个大标题处处都有小标题，让领导读起来舒服。

<p>结婚以前没有安全感，有一段时间会想，能把自己嫁出去吗？就很后怕。我以前爱抽烟。抽烟可能就是代表着精神上的一种小小叛逆。我不算是一个问题女孩，我在大学里面会经常逃课，但是我一直拿奖学金，学习也还过得去。

<p>童年我爸妈经常吵架，所以我童年应该是最缺安全感。我初中的时候，又遇到过一个很不好的班主任，我们班那个时候经常少钱，然后他就认为是我偷的，搞得我整整三年在初中就没有朋友，还会有人给我写贺卡说，生日快乐，少做三只手什么之类的。很郁闷。然后到了初三的时候，那个真正偷钱的同学被抓到了，让中班主任在班会上给我个清白，他不肯。班主任是教数学的，我以前数学很好，就这件事之后，我数学全毁了，我高考数学150分才考了70多分。幸亏语文挺好，其它的课挺好，所以还是考上了大学。那个老师真的很过分。当时我为了赌口气，考上了重点高中，我比我们那个省重点高11分，他居然说，你查错了吧？那时觉得已经到了快要看心理医生那么严重的地步了，因为到高中我在我们后来的数学老师那里写题时我的头就很疼，我都不想看。

<p><b>你的大学教育呢？</b>
<br>我大学里有部分的老师，让我很满意，但不是全部，因为有的老师明显是在应付，但是起码有两个老师是非常非常认真的。他们备课和教案也是质量很高，也会在课余来跟你交流一下。我想起来了，当时我觉得相对来说还是比较满意的，因为同学当中也有一些比较有意思的人，大家互相地影响着。因为我考的并不是很好的大学，所以我一直很羡慕那些读名校的人，我不知道他们的大学会怎么样，会不会学的东西更多一些，我觉得基本上大学四年真的浪费很多。

<p><b>西方观众会因为你们的出现而改变对中国的看法吗？</b>
<br>我不确定。短期的交流可能最多只能改变那些想改变看法的人。很多人都愿意给外国人贴上标签，就像中国人内部也会给上海人、河南人、北京人等等贴标签，这样会让他们自己感觉安全，而且在社交时也是很通用的谈资。

<p><b>你了解西方对中国的幻想或者恐惧吗？</b>
<br>不算了解，了解的也是媒体告诉我的。比如他们对中国女性的幻想可能是吕燕、章子怡、张曼玉那样的，幻想中国存在许多古老的东方文明遗迹、某些原始的神秘的巫术、李小龙、成龙那样的武林高手等等。恐惧也许有合法和非法移民对于他们就业机会的抢占，专制，不爱宠物甚至有野蛮的打狗运动，奇怪的饮食习惯，战争的可能性，低价倾销给当地企业的毁灭性打击等等。

<p><b>你想告诉西方什么？</b>
<br>我们有不同的人种，不同的历史、文化、政治、哲学、宗教，但其实大部分人都是平凡人，有着相同的生活需要和欲望，都有追求高尚的时刻，都有对于美好事物的渴求，当然也都会脆弱健忘虚伪疯狂等等。永远不要对于自己未知的人和事简单的下定义，这是最重要的。

<p><b>孔子、老子、释迦牟尼、默罕默德、耶稣有什么异同？</b>
<br>说不清楚。总体来说都是好人，不同在人生观上吧。感觉孔子属于相信世界可以通过某种秩序的设定变得更好的那类，总体来说比较乐观；老子则相信世界是可以无限的，七窍开而混沌死，更加渺茫一些，不过谈不上悲观还是乐观；释迦牟尼相信人自身可以修炼从而进入更好的世界；对默罕默德我完全没概念；耶稣我总觉得对人对己都很严格，太严格，似乎人们所做一切最多达到让世界不要更加差而已。

