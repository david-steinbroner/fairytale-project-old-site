<b>Interview 6: &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;：public functionary, female, born in 1980s, Hangzhou, Zhejiang</b>

<p><b>Please tell me about your current situation?</b>
<br>I am a secretary in a traffic control office of &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;. I took part in the entrance exams for postgraduate schools but failed. I didn’t expect to be doing what I do now. I wanted to teach in college or go abroad, in any case, I never thought of working in a government office, never. I have been working for five years and I am used to it. At least I was recognized by my colleagues. Generally I am satisfied with my life now, it’s not bad. My boyfriend and I just got married though we haven’t register. Because of him I focus my life on marriage, taking care of our dog or things like that. My job is just for salary. Now I learn to separate work and life clearly.

<p><b>What do you think of love?</b>
<br>Love is different at different ages and in different situations. I used to enjoy falling in love with someone secretly. Sometimes it’s a beautiful experience. It keeps you in a good state on and on, but it’s not stable. Later I found myself simply don’t know how to be with other people when I am in serious relationships. I don’t know what I am supposed to do when the relationship reaches certain place.

<p><b>Which fairytale influenced you most when you grow up?</b>
<br>Andersen’s <i>The Little Mermaid</i> touches me deeply. It was in elementary school, as I remember, I went to a classmate’s home and read that book there. At first I just wanted to read several pages, but I ended up reading the whole story and crying badly. I was extremely moved. That’s how I got the unrequited love thing.

<p><b>What makes you anxious most now?</b>
<br>My job. I have been a secretary for five years. I just finished the half year summing-up before I came here. That drove me crazy. We had to come up with different headings, divide the same content into small pieces, and write small captions for each big heading to make the leaders read more comfortably.</b>

<p>I felt insecure before I got married. Sometimes I wondered if I could get married at all. I used to smoke and for me smoking represents a kind of spiritual rebellion. I am not a problem girl. Although I often skipped classes in college, I always got scholarships and did well in my study.

<p>When I was a child my parents fought a lot. This is why I felt insecure in my childhood. In junior high I met a bad class teacher who thought I stole money from our class. Because of this I didn’t have any friends in the whole three junior high years. People even sent cards to me telling me not to be a thief. I was very much depressed. In the third year the real thief was caught but the class teacher refused to redress me. He taught mathematics. I was good at mathematics but after this my grades dropped seriously. I only got 70 points of the 150 point mathematics test in my college entrance exam. Fortunately I did well in Chinese and other subjects so I still entered college. That teacher was really out of line. I was admitted by a key senior high school and my grades were 11 points higher than the required points. But when he knew about my results he asked: “are you sure you the results are correct?” I almost wanted to see a psychologist because in high school every time I did mathematics questions I got headache. I couldn’t even want to look at those questions.

<p><b>How about your college education?</b>
<br>In my college some of the teachers are quite good, but not all of them, because some of them are obviously irresponsible. However, at least there are two teachers who are very earnest. Their preparation and teaching materials are of high quality and they often communicate with students after class. I remember I was rather satisfied with my college life. Some of my classmates were very interesting and we influenced each other mutually. It’s not a very good university so I always envy those in the famous universities. I wonder what their life would be and whether they can learn more, because basically for me much of the 4 years is a waste of time.

<p><b>Do you think western viewers will change their opinion about China because of your being here?</b>
<br>I am not sure. Short time communication only changes those who want to change. Most people like to label foreigners just like Chinese label people from Shanghai, Henan and Beijing. This makes them feel safe and it’s what people can talk about in sociality.

<p><b>Are you familiar with the fantasy or fear of western people about China?</b>
<br>Not really. All I know is from the press. Their fantasy about Chinese women might be those like Lu Yan, Zhang Zi Yi and Zhang Man Yu. They may think there must be many ancient oriental civilization relics, mysterious primitive voodoo and kongfu masters like Bruce Lee or Jackie Chan in China. They may fear that legal or illegal Chinese immigrants will steal their job, be against democracy, dislike pets or even do savage dog-hunting activities, or eat strange good. They may fear the possibility of war or devastating blow on local business by our massive dumping.

<p><b>What do you want to tell the west?</b>
<br>There are different races and different history, culture, politics, philosophy and religion. But most of the mankind is just ordinary people who share the same needs and desires. Sometimes we all long for beautiful and noble things but sometimes we relapse into madness and hypocrisy. What’s most important is never try to define people or things you don’t know.

<p><b>What’s the difference and sameness among Confucius, Lao-tzu, Sakyamuni, Mohammed and Jesus?</b>
<br>I don’t know clearly. Generally speaking they are all good persons. Maybe their views of life are different. Confucius is the kind of people who believes the world would be better if there is order and he is probably optimistic. Lao-tzu believes the world is infinite and we should keep ourselves ignorant and in chaos. He is neither optimistic nor pessimistic. Sakyamuni believes we can enter a better world by spiritual practice. I don’t have any idea about Mohammed. As for Jesus, I think he is too strict of other people and of himself, like the best we can do is not to make this world worse.

