<b>Interview 2: &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;, visual art student, female, born in 1980s, Jiangsu</b>
	

<p><b>Why do you study art?</b>
<br>At the very start I didn’t think of studying art. I began to learn painting since junior high school as an ex-curricular hobby, as time goes on, however, I started to feel this is what I want to do. And it’s partly because of the collage entrance exam. It’s difficult for me to enter a good university based on my grades unless as an art examinee. I’m also quite interested in Art Design. After so many years of learning, I have developed a kind of emotional attachment with it.

<p><b>What is the relation between art and life for you?</b>
<br>Art is everywhere in life. Things we eat, drink and use, packing, architectural design and signs on the road. I think our life needs art very much. In China, a sense of art is obvious lacking. Here in Germany, everything if full of art, such as the view in the streets and those posters in the underground passages. Everything is delicately designed, including buildings, simple and artistic. Buildings in Shanghai, on the other hand, are designed too artificially, internationalized without local peculiarity. 

<p><b>How do you feel about this exhibition?</b>
<br>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;’s exhibitions are always Chinese, but honestly speaking, some of them are beyond my comprehension. His works are genuinely Chinese, maybe it’s because exotic stuff is favored by international market. I have seen European art in other museums and I think good works of art always have their own national styles and ideas. 

<p><b>What’s your opinion about country?</b>
<br>Everyone has a nationality. A country is where we live. We are emotionally attached with it. Our county protects us, while we devote our life and career for it. Country is the mother of everyone. 

<p><b>How do you expect your future?</b>
<br>I want a clean and comfortable life.

<p><b>What’s the problem with China’s education?</b>
<br>I think our higher education is quite open and international.

<p><b>What’s your impression of Germany?</b>
<br>I learnt from history lessons that Germany is one of the defeated nations in World War Two. But after the war it realized its mistakes and rose again quickly. Its citizens are of great quality, well-cultured and prudent. When it comes to art, I don’t know much else except Grimm's Fairy Tales. On the streets people are all passionate and greeting each other all the time. This is what makes Asians different from Europeans. Asians are not passionate at all. For example, we run into a Korean old lady, who should be a famous artist, she was quite aloof with us. Some one familiar with her introduced her to us, then we said hello, but she was still very aloof. Europeans on the other hand, don’t put on airs like that. Another thing is the conductorless buses, it’s really conductorless. In China we have conductorless buses too, but there are monitors. It moves me that here everyone actually buys tickets voluntarily. 

<p><b>All you have said is positive, is there anything negative?</b>
<br>I didn’t notice anything negative.

<p><b>Do we still have Chinese cultural tradition?</b>
<br>We still have some. But everybody is thinking of developing internationally and Chinese culture is fading out. There are still people who are interested in traditional Chinese culture, but I don’t know much about it. I only learnt Confucius, Zhuangzi and Lao-tzu from high school text books and I never read them. 

<p><b>Do you long for love? How do you know of love?</b>
<br>Love is important for everybody. It’s our meat and drink, our spiritual pillar. It’s also a kind of creative motivity, a feeling of excitement, a feeling that your dream becomes true. When we were kids we read fairytales and got to know something about love. When we grow up, we are all gonna have some experience and some innocent ideas. Then we have to practice, to watch things that happen to our friends, and to receive teaching from our mothers about how to handle relationships.

<p><b>What do you think of sex?</b>
<br> I don’t see it as a serious issue. It’s no big deal. Everyone will have it, when you grow up to certain stage you just will do it. There’s no need to discuss it in a big way.

<p><b>Is there relation between sex and art?</b>
<br> There is. But some artists painstakingly overestimate it, and in some works of art there is too much of it. I think this is not necessary. 

<p><b>Does your contemporary have different opinions of sex with last generation?</b>
<br> Opinions change a lot. As a matter of fact we have been restrained about this and the restraining mainly comes from public opinions of last generation. I think Chinese tradition puts too much restraining on girls, while in the west people are quite open about it. When we reach certain age, we grow up and mature, and it’s not necessary to take this issue too seriously. It’s everyone’s need, everyone has such need. I think you understand what I mean.

