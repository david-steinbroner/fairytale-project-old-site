<b>受访者2。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;： 艺术大学生, 女，1980后，江苏人</b>

<p><b>你为什么要学艺术？</b>
<br>一开始没想到自己会学艺术。我从初一开始学画，本来是当作一种兴趣，后来就觉得自己想要往这方面发展。也是因为高考，因为高考需要，自己的成绩想要考非常好的学校很不容易，就想通过艺术来达到吧，而且对艺术设计也蛮有兴趣的，学了几年之后，有一种感情。

<p><b>你觉得艺术和生活是怎么的关系？</b>
<br>感觉生活到处都是艺术啊！我们吃的、喝的、用的、包装，那些房子的设计、路上行走的一些标记，感觉我们的生活很需要艺术，我们中国的环境就明显地少了一种艺术感。德国这里，像我们在这里看到路上的、地下通道里帖的那些海报，随便一张信手拈来，都特别有艺术感，都是经过精心思考的。还有房子的设计，简洁，也很有艺术感。像上海的房子设计得太做作了，太追究国际化，没有自己的个性。

<p><b>看展览有什么感受？</b>
<br>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;的展览都是很中国化的，但说实话，有的不知道要表达什么意义。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;的作品一看就是我们中国的，可能在国际上大家都喜欢比较民族化一点的作品。我在其它一些展览馆看到欧洲的作品，感觉每一个好的作品都有自己的民族风格和思想在里面。

<p><b>你怎么看待国家？</b>
<br>我们每个人都有自己的国籍，国家是我们赖以生存的地方，有一种感情色彩在里面。国家是用来保护我们的，我们以后的成长、工作也是为国家做贡献，国家是每一个人的母亲。

<p><b>你对未来有什么设想？</b>
<br>我想要一种纯净、安逸的生活。

<p><b>你认为中国的教育存在什么问题？</b>
<br>我们大学的教育是很开放性的，与国际接轨。

<p><b>你对德国的印象怎么样？</b>
<br>以前学历史，知道二战德国是战败国，可是它在战后认清了自己的错误，又迅速地崛起了。公民素质很高，底子又好，而且还很严谨。艺术方面，就知道《格林童话》，其它不太了解。
大街上所有人都很热情，看到了都主动打招呼。亚洲人和欧洲人的差别也在这里，亚洲人非常不热情。比如我们在大街上遇到一个韩国老太太，也应该是有名的艺术家，她对我们非常地冷淡。因为有人认识她，向我们介绍她，然后我们和她打招呼，她也还是非常非常冷淡，而欧洲人，感觉就没有什么架子。像无人售票车，彻底是没有人售票。中国也有，但有人监督，这里的人都自觉地买票，让我特别感动。

<p><b>你说的都是好的方面，有没有差的一面？</b>
<br>差的一面没发现。

<p><b>我们是不是还有中国文化的传统？</b>
<br>还有一些。但大家都想着向国际方面发展，渐渐淡化了中国的文化。有的人朝中国文化发展，但自己本身对中国文化也没有特别深刻的了解。孔子、庄子、老子么都是课本中学的，自己没读过。

<p><b>你是否憧憬爱情？你是如何了解爱情的？</b>
<br>爱情对每个人都很重要啊，是精神寄托，精神支柱。它也是一种创作的动力，一种兴奋的感觉，一种榜样，实现梦想的感觉。小时候我们都看童话，都会了解一些，长大之后，我们都会有一些经历，一些自己懵懂的想法。然后就是实践一下，还有周围朋友发生的事情，还有妈妈的教导，教导怎么去处理感情的问题。

<p><b>你怎么看待性这个问题？</b>
<br>不要把它看得很严重，不是什么重大的问题。每个人都会有，成长到一定阶段，都会去实践吧，不需要大张旗鼓地拿来讨论。

<p><b>艺术和性之间有关系么？</b>
<br>有。但是有的艺术家故意、有意地去夸大这方面的问题，有的作品性方面已经泛滥了，感觉没必要。

<p><b>你觉得你的同龄人在性问题上的看法和上一代相比有变化么？</b>
<br>有很大变化。其实我们在这方面很有束缚，我们的束缚主要来自于社会的舆论，社会的舆论主要是我们的上一辈。我觉得中国的传统对女孩子束缚特别多，像在外国应该是很开放的事情吧。我们到了一定的年龄，人成长了，已经到了成熟的阶段，不一定把这个问题看得太严重，这是每个人的需要，每个人都有这样的需要。你知道我的意思吧？

