<b>受访者27。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;： 公司职员，男，1950后，浙江人</b> 

<p><b>你看到展览了吗？有什么感想？</b>
<br>看了，有很多还是看不懂。 &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;那个倒掉的东西，我也去看了，很有震撼力，可惜没看到当初建好的那个效果。他很多东西我都看过，我一直都很关注他的东西。这个《门》确实是很震撼的一个东西，挺大气的，他有想法。我认为他是一个观念很新的现代艺术家。

<p><b>你对现代艺术感兴趣吗？</b>
<br>我也就是喜欢吧，但挨不上边，因为我是做出版的。最早出版的大多数是文学作品，后来转到了传统文化的一些东西，也从传统文化中整理了很多道教的东西出版，后来还出版了一些和人民生活密切相关的东西。

<p><b>你觉得道教算不算是一种宗教？</b>
<br>它算中国本土的一种宗教，佛教是外来的，基督教也是外来的。中国现在有五大宗教，道教也算是宗教，算是最早的、本土化的。人们总觉得道教里有迷信的成份，有占卜的成份，但是道教里有很多对人类贡献很巨大的东西，比如人类健康方面，太极拳风靡全球，最早的太极拳是属于道教的。世界上一共是两大医学，一个是叫西医，另一个是叫中医，中医也算是属于道教的，俗话说十道九医嘛，以前皇帝他们延年益寿，就是用了很多这方面的高人术数，道士啊，炼丹啊，希望长命百岁。

<p><b>道教的宗教观念不是特别强吧？</b>
<br>佛教宣传得厉害。我曾经跟中国道教协会联系，说世界佛教大会在我们国家开，这是一个信号，我们需要宗教来配合，和谐社会没有宗教的东西，你靠共产主义不能完整，怎么弄现在都不行，佛教这个东西是外来的，那么只有道教是本土的，现在很多领导都是讲和谐，也是出于道家的。

<p><b>现在国内说中医无用或者是中医害人，你怎么看？</b>
<br>这些都是不科学的。我认为中医还是比较好的，当然对有些病，中医治疗不了，但是完全排斥它，那肯定是很粗暴的一种行为，是吧？毕竟，它对人的调理肯定是有益处的。

<p><b>那占卜不算是卜卦？</b>
<br>那就不算了。那个占卜方面的东西，你用科学的道理讲，是无法解释通的。但是它已经延续下来了几千年，也有它存在的道理。

<p><b>你相信有鬼么？</b>
<br>听一些高人讲过，就是说有些人的身体里存在一种东西，这种东西不死掉，这个人整天就不安宁，等到那个东西剔除掉了，人就又完整了，就可以吃饭啊睡觉啊，一切心理都正常了，要不然的话，整天就是过不去，整天就是在那个圈子里面，是一种病态。
<p>我周围见过好几个人有，比如他们晚上睡觉的时候，永远都是闭不上眼睛。他为什么闭不上眼睛？因为他一闭上眼睛的话，就觉得有小孩坐在他旁边，他就吓死了，他就不敢睡觉，他每天灯一关以后，就不敢睡觉。还有一次——他也被吓了一阵子，他们一些人在一块喝酒，他啤酒根本没喝，但是杯子里的啤酒就哗哗地下去了，他就感觉很害怕。后来这事给解决了，也是找人给他做个所谓的“捉鬼”，就给他捉掉了。
<p>他找的能捉鬼的那个人，开始只是问他，你给我看看，我这个人怎么样，能捉鬼的那个人说，你问题大了，他说怎么了，捉鬼的人说，你身上有不干净的东西，这一说，他又吓得一身冷汗。他说，那我该怎么做，捉鬼的人说，你不要着急，你去买一坛米酒，那种不能透明的，不能有光的，买来以后倒掉酒，坛洗干净。洗干净以后，捉鬼的人用一块黄的绸缎一抓，就给抓出来了，然后放在那个坛子里封住，然后那个坛子冰凉冰凉的，比那个冰都可怕。从那以后他心里就好了，就过去了。

<p><b>你觉得中国人有信仰吗？</b>
<br>大多数没有信仰。我有信仰，我多多少少有一些吧。因为没信仰的话，那是很可怕的，什么事都做得出来。

<p><b>你觉得中国传统文化保留得好吗？</b>
<br>不好，破坏得多啊，比如说很多建筑，都搞掉了，弄了一些不伦不类的建筑取代，很可惜。像我昨天下午去了他们那个展馆，一直走过去，就是一片风景很好的皇家园林。我看到那片地真的好，要是我们国内某个房地产商的老板，可能就瞄准那块地就去盖楼了，买房子肯定是高价，但是国外人不会这么干。

<p><b>你觉得在北京压力大吗？</b>
<br>当然大，这没有说的，就是必须得做事。总是觉得有很多的事要去做，有很多的这想法要去做，然后就怕自己搞得烦闷。所以感谢&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;先生给我提供了一次放松学习的机会。

<p><b>中国的图书出版业怎么样？</b>
<br>糟糕，很差很差，中国的出版业总是处在一种混乱之中。若干年后，相信它能好起来，需要有相关的法律来完善。现在就是一本好书出来了，盗版书马上就跟着出来，给真正做出版的人带来了很多的困难和阻力，做得“好”的，就是所谓挣钱了的。不过，有一些是挣了钱没有名气，有的是有了名气没有钱。真正的好书被少数人接受，而畅销书是可以流行的，是给大多数人阅读的。

