<b>Interview 27. &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; : Office worker, male, born in 1950s in Zhejiang</b>

<p><b>Did you see the exhibition? What do you think of it?</b>
<br>I saw it, there were lots of things I didn't understand. &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;'s collapsed thing, I also saw that, it was stunning, it's a pity I didn't see what it looked like when it was first built. I've seen a lot of his things; I've always paid attention to his work. "Template" is really a stunning piece, very grand and full of thought. I consider him a contemporary artist with very novel ideas. 

<p><b>Are you interested in contemporary art?</b>
<br>I do really like it, but it's somewhat irrelevant since I work in publishing. We publish literature for the most part, followed by works of traditional culture such as compilations of Daoist writings, and then we also publish things that relate to the people's lives. 

<p><b>Do you consider Daoism a religion?</b>
<br>It's regarded as one of China's native religions, Buddism and Christianity are imports. China now has five main religions. Daosim also is considered a religion, the earliest and most native one. People always think there are aspects of superstition in Daosim, there are notions of divinity, but Daosim devotes a great deal of things to human nature, such as humanity's health. Taichi is popular worldwide, the earliest forms of taichi were part of Daoism.  Worldwide, there are basically two types of medicine, one is called 'Western' medicine, and the other is Chinese medicine. Chinese medicine also stems from Daoism, as the proverb goes: "ten ways nine cures," in the past, emperors would seek longevity, they would employ many talented diviners and Daoist priests to concoct immortality elixirs in order to live happily for eternity. 

<p><b>Is Daoism's religious ideology very rigid? </b>
<br>Buddhism is awfully proselytizing. I was once speaking with Chinese Daoist leders about the Buddhist convention, taking place in our country. It's a sign that we must cooperate as religions, harmonious societies don't have religious matters, but you can't completely depend on Communism for support, no path is certain nowadays. Buddhism is a foreign import, there's only Daosim that's indigenous. Right now a lot of leaders speak of "harmony," that also takes its source in Daoism. 

<p><b>Nowadays people in China are saying that Chinese medicine is useless or that it even is harmful, what's your opinion?</b>
<br>It's not science. I still think Chinese medicine is rather good. Of course there are certain diseases it can't cure, but to completely reject it would be quite cruel, no? After all, it must have some healing benefits. 

<p><b>Isn't divination equivalent to fortune-telling?</b>
<br>No. You can't explain divination by scientific process. But it's lasted over several thousand years, there's also some justification in its longevity. 

<p><b>Do you believe in ghosts?</b>
<br>I've heard wise people speak of them, they say there are people who have something inside themselves, something that doesn't go away when they die. These people are restless and troubled all day long, waiting to rid themselves of that something. These people are intact, they can eat and sleep, their feelings and emotions are completely normal, but these things make their lives difficult, they are entrapped in this morbid state.

<p>I've seen many people like this in my surroundings, for example, when they try to go to sleep at night, they can never shut their eyes. Why can't they fall asleep? It's because as soon as they close their eyes, they think they see small children sitting at their side, they're scared to death and don't dare sleep. Every night after they turn out the lights, they don't dare fall asleep.

<p>Then there was one time --- He was scared for a while, he was with people at a bar, he hadn't even had one beer, but the beer in his glass gurgled and disappeared, he was very afraid. Later, this story was resolved when he found someone to perform a so-called "ghost cleanse" to get rid of the ghost. He found a person who could catch ghosts, he started to ask him: "Take a look at me, I'm this way." The ghost catcher said, "Your problem is great." He said, "You have unclean things within yourself." He broke into a cold sweat upon hearing those words. He said "Then what should I do?" The ghost catcher said, "Don't worry, go buy a jar of rice wine that's not transparent, empty it out and clean it. After you've cleaned it, [I] the ghost catcher will use a piece of yellow satin to catch the ghost as it emerges, then will confined it to the jar. Afterward the jar will become ice cold, even colder than ice." From then on, his soul was peaceful.

<p><b>Do you consider Chinese people to be religious?</b>
<br>The majority doesn’t believe in any faith. I have faith, to some extent. Because it's very scary if you don't believe, anything can happen. 

<p><b>Do you think traditional Chinese culture has been well preserved?</b>
<br>No, it's been very damaged, for example, a lot of the architecture has been torn down, it's been replaced by nondescript buildings, it's a shame. Like yesterday afternoon, I went to the exhibition hall, the entire way the scenery was beautiful in the royal forest. The views I saw were really great, if it were up to our country's shop owners, maybe they would just aim to buy the land and build buildings everywhere. Of course, it's very expensive to buy a house, but foreigners wouldn't do things this way. 

<p><b>Do you find Beijing very stressful?</b>
<br>It's certainly stressful, it goes without saying, there’s a lot to get done. I always feel like there is so much to do, so many ideas to realize, on top of that I'm afraid of getting anxiety. Therefore I'm very thankful to Mr.          for providing me the opportunity to relax and learn a little. 

<p><b>What is China's publishing industry like? </b>
<br>It's awful, really terrible, terrible, China's publishing industry is always in a state of chaos. In a number of years, I believe it will start to get better, for that to happen the related laws need to be perfected. Nowadays, when a good book comes out, the pirated version follows immediately; this creates huge obstacles and difficulties for the real publisher to do "well," that is, to make money.  But there are people who earn money but no fame while others are famous but penniless. A few people appreciate a genuine well-made book, yet bestsellers become popular by being accessible for the great majority to read. 

