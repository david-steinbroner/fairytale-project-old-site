<b>受访者23。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;（&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;）：作家，男，1960后，北京</b> 

<p><b>你老喝酒么？</b>
<br>我一般是见人就喝，不见人就不喝。

<p><b>为什么见人就喝？</b>
<br>紧张啊。不知道该说什么，喝点就知道了。

<p><b>我也觉得你挺害羞的。</b>
<br>可能是吧。当然不喝时间长了，也想，也不全是为了消除紧张。有时候喜欢喝大的状态。

<p><b>那你平常整天在喝酒么？</b>
<br>跟朋友在一起，差不多就是这样。

<p><b>那喝这么多，会不会对身体不好啊？</b>
<br>会，但不喝这么多，会对精神不好。

<p><b>你现在还在写作么？</b>
<br>还写。这几年老不在北京，每年差不多有半年不在，有时候是帮人代课，更多的时候是找个地儿一个人呆着，只有一个人呆着的时候，才有时间写东西。在北京，气氛比较浮，朋友也多，没法静下心来写，很难控制那种浮躁。也许狠狠心也能行，但很难，就算朋友不找我，我也会想出去找他们。

<p><b>你很喜欢你的朋友，希望大家都在一起？</b>
<br>对。

<p><b>那算是一种群居么？</b>
<br>在北京基本上就是一种群居，或者说过一种集体生活，每天不是这儿，就是那儿，到点就去上班，然后喝晕了就回来。

<p><b>喝酒对创作有帮助么？</b>
<br>我觉得像我们这种喝，肯定没必要，不仅没帮助，创作还毁了。

<p><b>你觉得用颓废来形容你，准确么？</b>
<br>怎么叫颓废？自暴自弃的意思？

<p><b>就是在这个比较现实的社会里主动地放弃了一些进取的可能。</b>
<br>没有，我觉得不是。我放弃的东西，实际上都挺表面的，比如工作。实际上，我还是喜欢名、利、色，只不过不以常人的手段来追求罢了。

<p><b>作为一个作家，你对什么样的东西感兴趣呢？</b>
<br>可以这么说吧，以前是对青春期各种烦恼的记录，现在是对中年期各种烦恼的记录。在记录过程中分析分析，可能会稍微有一些缓解吧。

<p><b>你要缓解的是什么呢？</b>
<br>缓解……有时候不写，会觉得不大舒服。可能还是在寻找意义吧，觉得在写作过程中挺有意义的。缓解那种屈辱感。

<p><b>这种屈辱感是怎么形成的？</b>
<br>有些东西明摆着，就是我们不知道的，并且挺可怕的。一般人可能不去看，但稍微多想想，就会觉得屈辱，我不知道该不该叫屈辱感。这种感觉不知道是怎么形成的，而且分阶段……要不就是不同程度的抑郁症？我也搞不清楚。

<p><b>你读不读佛教的书？</b>
<br>我对这种宗教的东西，一阵一阵的，比如说前两年，有一阵特别喜欢佛教，就狂读了一阵，什么事一岔开，就放下了，不知道又去读什么了。去年又突然特别喜欢基督教，然后读了一部分，又放下了。反正文学类的读得越来越少，宗教、哲学读得越来越多，好像很多人都是这样。

<p><b>你怎样看待爱情？</b>
<br>我以前还对爱情挺迷恋的，甚至还点宗教那种感觉——美好，让人上升。但随着年龄、精力的增长，虽然还是美好，但有点玩不动，得不偿失，因为你要花特别多的精力来维系这份感情，我觉得有点划不来……而且每次美好都是重复的。

<p><b>那你觉得对一个女性产生爱情需要智慧么？</b>
<br>不需要。

<p><b>你将来还会发生爱情么？</b>
<br>我觉得会的。只要性激素还在分泌，就不能避免吧。

<p><b>你觉得爱情和冲动有什么区别么？</b>
<br>性冲动？还是爱情的冲动？简单说，爱情的冲动和性冲动是一致的，没法分开的。比方说，嫖妓就不行，因为不认识，她陌生，长得再漂亮也不行。

<p><b>你为什么不结婚？</b>
<br>我觉得这话要倒过来问，为什么要结婚啊？要结婚可能是因为这个社会要求从个人上变成一个有序的东西，结婚、家庭都能使个人变得有序，从而让这个社会变得安全一点。这是从社会角度上来说的。从个人角度上说，爱情肯定是有期限的，两个人结婚之后，过日子、养孩子、上班、也不怎么吵架，这种日子是我认为比较理想的，但这种前景我是不能太接受的。因为这样，两个人又一方又谈恋爱了怎么办，除非两个人都特明白，谁碰上了就谈，然后和平分手。

<p><b>你一般一段恋爱的时间会保持多久?</b>
<br>我以前交过两个女朋友，都是5年一个。

<p><b>还蛮长的。</b>
<br>可能也跟那个年代有关系，那是在90年代。进入新世纪就没那么长了。

<p><b>那进入新世纪以后有多久啊？</b>
<br>2、3个月，半年，小一年。以前的两个都是和我差不多大，或者比我小一点。但现在都是80后，可能也有关系吧。

<p><b>父母对你的影响大么？</b>
<br>肯定大，但我对他们没什么亲情。因为我是从小被姥姥带大的。我父母是大院的，是干部。他们其实也不知道怎么带孩子。他们现在的身体非常不好，我妈现在老年痴呆，在床上基本不能自理，我爸也是拄一个拐，颤颤巍巍的，这是让我最苦恼的一事，让我没法彻底离开北京。

<p><b>中国和西方对你有什么含义？</b>
<br>以前是通过电影来感受西方的，这次亲身感受，觉得这边比较安静、干净和踏实，这是以前从媒体上体会不到的。可能是中国了解西方比西方了解我们更多一点，可能是我们在追他们吧，所以希望多了解一些。

<p><b>许多西方人也喜欢佛教，但可能是很少数，不本质，就像我们喜欢摇滚乐。</b>
<br>因为他们没在我们这里生活过，也是通过媒体来认识我们。

<p><b>你比较关心什么样的公共话题？</b>
<br>生、老、病、死。

<p><b>你关注环保之类的问题么？</b>
<br>我最近半年对教育问题比较关注，因为我在代课，像环保啊、能源啊、包括像独裁啊这些问题也就说说而已，不像我关注教育这样切身，因为在学校呆着，有切身感受。很明显，这边（卡塞尔）没什么污染，天气好，中国天气不好。

<p><b>你觉得中国的教育有什么问题？</b>
<br>我说不好，但我觉得可能整个现代教育就不对，不论是中国的还是西方的。这边学校可能确实要比我们那边要好，像没有围墙，但大体上都一样，都是学校。不能说缺陷吧，但是讨厌，自从幼儿园开始，我就不愿意上幼儿园，不愿意上小学，不愿意上中学，不愿意上大学，上也是就强伮着上，学习好也是强伮着学校好，一直就是这么硬着头皮被迫着过来的，完全不是情愿的，完全就是不好的东西。包括家庭也是，从小就有一种不如意，对着干，觉得不好。

<p><b>你通过教书发现一些什么问题？</b>
<br>就是学生不爱学，厌学……这个我早就知道，但是他们现在厌学的程度比我们那时候更高，可以用“出离愤怒”来形容。

<p><b>这种愤怒的原因是什么呢？</b>
<br>就是从小到大这种教育体系不对吧，挺违反人性的。

<p><b>什么样的教育是不违背人性的？</b>
<br>边吃边喝边聊。

<p><b>国外的教育体制可能比我们要好很多。</b>
<br>对，像我们的老师，一个可能带一百多个学生，这边一个老师带十个。老师的素质不高吧，没什么智慧，学校不找可以传道、授业、解惑的人当老师，完全照本宣科，也不找那些真正好学的真正有困惑的学生。其实很多人是不需要受什么教育吧，学校完全就找那些不需要受教育的学生。

<p><b>你自己有没有信仰？你周围的朋友有么？</b>
<br>没有。周围有的人有。

<p><b>你怎么看待&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;的《童话》这个作品？</b>
<br>非常好，能给人以参与性。只要你卷进来，就会有各种各样的事情和感受，这样的艺术和行动是有意义的，起码非常好玩。而不是博物馆那些艺术、作品，离我们不懂艺术的人完全不着调，让我们根本无法去感受，除非我们谄媚的去看，否则，任何一个不懂艺术、有理性的人不会感兴趣。

<p><b>你对德国有什么印象？</b>
<br>空气好，人单纯、热情、朴实，狗也温顺，人懂礼貌。我最烦中国那种开车在你面前急刹车的，他们这边车让人。

<p><b>除了这些呢？</b>
<br>住咱们旁边的德国人，感觉他们挺孤独的。

<p><b>你觉得自己孤独么？</b>
<br>没有觉得。

<p><b>我们早年的时候读西方的作品中对西方异化、幻灭的描述，你觉得准确么？</b>
<br>我觉得准确，离这种所谓幻灭，异化更近。尤其是‘幻灭’，中国因为太热闹了，所以大家都没有幻灭感，大家好像都特有用。他们这边现实，具体的目的不强烈，所以可能更容易体会到幻灭吧。



