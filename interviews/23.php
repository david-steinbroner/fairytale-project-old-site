<b>Interview 23: &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;: author, male, born in 1960s in Beijing</b>

<p><b>Do you always drink alcohol?</b>
<br>I usually drink when I'm with people, I don't when I'm not.

<p><b>Why do you drink when you're with people?</b>
<br>I get nervous. I don't know what to say, after I drink a little I figure it out.

<p><b>I get the sense you're also shy.</b>
<br>Maybe. But when I don't drink for a long time, I think that maybe I don't always drink to
conquer my nerves. Sometimes I like to drink to grand occasions.

<p><b>Are you often in bars all day long?</b>
<br>When I'm with friends, it's more or less that way.

<p><b>Isn't drinking that much bad for your health?</b>
<br>Yes, but not drinking that much is bad for the spirit.

<p><b>Are you still writing books?</b>
<br>I still write. These past few years I haven’t been in Beijing often, I'm gone around half
the year, sometimes substitute teaching, more often I'm looking for a place to be alone,
only when I'm alone do I have time to write. Beijing is lively, my friends are there, it's
hard calm myself to write, it's hard to control this restlessness. If I'm very resolute it
works, but it's very hard, even if friends don't call on me, I'll go out and seek them.

<p><b>You really enjoy your friends, do you wish for everyone to be together?</b>
<br>Yes. 

<p><b>Like in a collective?</b>
<br>Beijing is basically a collective, you could call it a social lifestyle, everyday, everywhere,
you work till you're done then you go home when you're drunk.

<p><b>Does drinking help your creativity?</b>
<br>When you drink like we do, drinking isn't essential to creation, not only does it not help,
it can ruin creativity.

<p><b>Do you think "decadent" is an accurate description of you?</b>
<br>Decadent? As in given up caring, abandoned to despair?

<p><b>As in, the societal reality of abandoning one's motivations to carry on.</b>
<br>I don't think so. The things I've given up are in reality quite superficial, like having a job.
Actually, I still enjoy fame, profit, looks, it's just that I don't pursue them by the same
means as ordinary people.

<p><b>As a writer, what interests you?</b>
<br>You could put it this way: before I was interested in recording the frustrations of
adolescent life, now it's the vexation of middle age. By analyzing these records, maybe I
relieve things a little.

<p><b>What do you seek to relieve?</b>
<br>Relieve.... sometimes when I don't write, I feel uncomfortable. Maybe I'm still seeking
the meaning of all this, I feel there's meaning in writing about these events. I ease the
feeling of humiliation.

<p><b>What form do this humiliation take?</b>
<br>Something is clear: we're afraid of what we don't know. Most people don't think about
it, but if you do think about it, you feel humiliated. I don't know if this feeling should be
called "humiliation", I don't know what form it takes, but in those stages of life.... how
about a certain type of depression? I don't really know.

<p><b>Do you read Buddhist texts?</b>
<br>I deal with religious things in bursts, two years ago, I had a moment of appreciation
for Buddhism, I read like crazy for a bit, but when something else distracts me, I'll put
it down, I don't know when I'll pick it up again. Last year I suddenly got interested in
Christianity, I read it a bit then set it aside. In any event, I read less and less literature and
more religious texts and philosophy, it seems like a lot of people are that way.

<p><b>What are your views on love?</b>
<br>I used to be infatuated with love, almost religiously -- beauty is elevating. But energy
decreases with age, even though there is still beauty, it's less worth pursing, the gains
don't make up for the losses, since you have to spend to much energy to maintain that
feeling, it's not always worth it.... besides, every beauty is a replica.

<p><b>Do you think you need wisdom to fall in love with a woman?</b>
<br>No.

<p><b>Do you think you will fall in love in the future?</b>
<br>I think it's possible. As long as my body still secretes sex hormones, it can't be avoided.

<p><b>What's the difference between love and an emotional impulse?</b>
<br>Sex drive? or romantic drive? Simply put, love's romantic and sexual impulses are the
same thing, they can't be separated. For example, a prostitute won't do it, because you
don't know her, she's a stranger, even if she's beautiful it won't work.

<p><b>Why haven't you gotten married?</b>
<br>I think the question needs to be reversed, why get married? The need to get married
comes from societal norms that need every person to live according to order, marriage,
families all are part of becoming an orderly person, from whence derives a more secure
society. That's from the societal angle. From my personal point of view, love is fleeting,
I think it's an ideal situation when two people get married, live their lives together, raise
children, go to work and don't fight often, but this prospect doesn't suit me. Because in
that situation, what do you do when one person falls in love? Only when both completely
understand that whoever cheats immediately brings it up, then they can break up
peacefully.

<p><b>How long does love usually last?</b>
<br>I've had two girlfriends in the past, both relationships lasted five years.

<p><b>That's still pretty long.</b>
<br>Maybe it had something to do with the time, it was the 90s. My relationships got shorted
in the new century.

<p><b>How long have they been in this century?</b>
<br>2, 3 months, half a year, almost a year. Before, they were all around my age, or a little
younger. Now, they're all post-80s [born after 1980], maybe that also has something to do
with it.

<p><b>Did your parents have a great influence on you?</b>
<br>Definitely, but I don't really feel any affection towards them. My grandmother raised
me. My parents were communist party cadres. They really didn't know how to raise kids.
They're in poor health now, my mother has Alzheimer's, she's bedridden and can't take
care of herself, my father walks with a cane, shakily. It's the most distressing thing in my
life, because of it I can never really leave Beijing.

<p><b>What connotations do China and the West bring to mind?</b>
<br>Before, I had only experienced the West through movies, this time I'm discovering it in
person, it's cleaner and more down-to-earth, you can't know this by only watching the
news. Maybe China understands the West a little more than the West understands us,
maybe we're pursuing the West therefore want to know more about it.
<br><br>A lot of Westerners also like Buddhism, maybe they are few in numbers, but not in
essence, like the way we like rock'n'roll.
<br><br>Since they haven't lived in our place, they also only get to know us through the media.

<p><b>What common conversation topics engage you?</b>
<br>Life, aging, illness, death.

<p><b>Are you concerned about environmental issues?</b>
<br>Recently, since I've been teaching this past semester, I've been more concerned with
issues in the education system, thinks like the environment, energy, upholding dictators,
these things are just hot air, not as concerning to me as the problems in education, since
I'm the school system, I'm personally affected. It's clear though, that there's no pollution
here (in Kassel), the air is good, it's not in China.

<p><b>What to you think is wrong with China's education system?</b>
<br>It's hard to explain, but I feel like the entire modern education system is wrong, whether
in China or the West. The schools here may truly be better than ours, they don't seem
enclosed, but overall they're all the same, they're all schools. Not to list flaws, but I hated
going, I didn't want to go to kindergarten, I didn't want to go to primary school, I didn't
want to go to high school, I didn't want to go to university, I stubbornly resisted going
and becoming a good student, I always had to brace myself to be forced by the system,
completely against my will, it was terrible. I also struggled with my family, it wasn't
good.

<p><b>What problems have you encountered as a teacher?</b>
<br>That students don't like to study, they loathe studying... I realized that early on, but their
loathing of studying is even greater than mine was, you could describe them as "angry
youths."

<p><b>What makes them angry?</b>
<br>It's this bad education system since they were little; it's really against human nature.

<p><b>What kind of education would follow human nature?</b>
<br>Eating, drinking, conversing.

<p><b>Education systems abroad may be much better than ours.</b>
<br>Yes, like our teachers each have to teach over one hundred students, here they each teach
ten. Teachers aren't very capable or knowledgeable, schools don't seek teachers who
can lecture, instruct and explain, it's completely by the book, they also neither seek out
students who genuinely want to learn nor students who truly don't want to. In reality, lots
of people don't need to be educated like this, schools still seem to find all the students
who don't want this kind of education.

<p><b>Are you religious? Is your circle of friends?</b>
<br>I'm not. Some of my friends are.

<p><b>What do you think of &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;'s piece "Fairytale"?</b>
<br>It's really great, letting people participate. Just by coming, you experience all different
kinds of situations and experiences, this kind of art and endeavor is really meaningful,
and at the very least it's a lot of fun. It’s also not like museum art, that’s not accessible
to us who don’t understand art, and doesn’t give us the means to understand it, unless
we look at it subserviently, otherwise, any rational person who doesn’t understand art is
unlikely to be interested.

<p><b>What's your impression of Germany?</b>
<br>The air is clean, the people are simple, friendly, down-to-earth, even the dogs are docile.
Germans understand politeness. The most vexing thing in China is when drivers screech
to a break right in front of you, here cars yield to pedestrians.

<p><b>Anything else?</b>
<br>Living next to Germans, it feels like they're rather solitary.

<p><b>Do you think you are solitary?</b>
<br>No, I don't.

<p><b>When we're young, we read about alienation and disillusionment in Western works, do
you think they're descriptions are accurate?</b>
<br>I think they're accurate, alienation and disillusionment feel very close to here.
Especially "disillusionment”, because china is so bustling, no one feels disillusioned, they
all feel like they have a specific purpose. Here, concrete motivations aren't very strong, so
maybe it's easier to become disillusioned.

