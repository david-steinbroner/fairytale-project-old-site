<b>Interview 24: &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;: Publishing house web editor, female, born in 1980s in Hunnan</b>

<p><b>Can you speak a bit about your work experience in the past three years?</b>
<br>I've changed jobs two, three times in three years. I studied finance, the last two jobs
where in business. In Beijing, finance jobs aren't that great, so I found a job at a
software company as a project assistant to engineers. After a while, I wanted a change of
atmosphere so I found a job at a publishing house as a web editor, I think I want to keep
developing in this field.

<p><b>Did your friends have similar experiences, switching to jobs that had nothing to do with
their majors?</b>
<br>Yes, some people did market research. In university, you're not only learning about your
major, you’re also learning how to learn, as well as the ability to be trained. Nowadays,
a lot of university students' jobs have no relation to their majors; this phenomenon isn't
necessarily good or bad. Of course, some people are pressured by the need to make a
living or by society, so if they can't find a job in their area of study, they give up and go
do something else. Also, maybe you're more ambitious right after you leave school, then
you discover you can't handle the job you set out for, so you lower your expectations and
settle for a more basic job. And then there are some people who realize, after working for
a while, that they're not that interested in the job they have, so a change of career happens
naturally. In short, some people are pressured and forced in their choice of jobs, others
are motivated by their interests in the work.

<p><b>Was your decision due to pressure or interest?</b>
<br>Mine was out of interest.

<p><b>Now that you've arrived [in Kassel], is this place different than you expected?</b>
<br>At first, I thought that by organizing this many people and sending us the same clothes,
we would be participating in collective activities, as in some piece of performance art.
But after I got here, I explored things for myself, just looking around and having fun on
my own, I was a little surprised that there were no collective performances. Originally,
I thought we were meant to act as manifestations of &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;'s philosophy, which would have been fine, but in fact, he didn't want us to manifest anything, he just wanted
us to participate. I think this way is great.

<p><b>Did you see the works in the exhibition?</b>
<br>I feel like I've only seen a few. Yesterday morning it was my turn to wash dishes,
only once I was done could I go out. Outside, I explored Kassel, experiencing the
surroundings and ambiance. I went to the Grimm Brothers' Museum. On the way back,
I saw an artwork in a church, lot of cardboard was piled up into a sculpture, I couldn't
clearly figure out what it was. It was pitch-black, there was a screen and someone playing
piano. Today I went and saw the castle; inside there were classical paintings. Honestly,
maybe I don't really understand these things, I don't feel like I understand classical
paintings, but I also don't really understand modernist works, maybe there's an aspect or a
line that expresses something, but it's not clear to me.

<p><b>Are you currently single or married?</b>
<br>It's interesting, when I signed up I wasn't married, I was after I was chosen. We met when
we were students. We've received the wedding certificate, but we still haven't arranged
the ceremony or the reception or anything. The events leading up to this event were
very short, but falling in love wasn't that way at all. At the end of February I signed up
for "Fairytale", on March 8th I got married, in the last third of March I received notice
that I had been chosen. I remember them saying all the notification emails would be sent
out before March 20th, I only got mine on the 19th.

<p><b>Do you think people are still sexist nowadays?</b>
<br>Some are. A classmate's colleague had two girls, then got divorced. In the mountains
of Guandong, families really favor boys over girls, men are the most important. After
having girls, southern parents aren't willing to take care of them, the little girls look at
them, call for them but they don't pay them any attention, it's as if having girls is like
having enemies. I read in the news that a after giving birth to a girl, the woman's family
wasn't happy, so she went crazy and immediately threw the baby from the hospital
window. Even though these situations are becoming less frequent, they still happen,
especially in the rural mountain areas in Fujian and Guangdong, a lot of people still think
that way.

<p><b>When your economic situation permits it and both parties mature, would you like to have
one or two children?</b>
<br>The more the better. Recently, I've been watching TV series "Kids in the house" by Song
Dandan. Two marriages unite as a big family, the husband had a grown-up daughter and
a young son; the wife has a son, they make up a very warm and happy family. This is
obviously a little far from reality.

<p><b>Did you come to Beijing to create a new world for yourself?</b>
<br>I came on my own. My boyfriend was studying in Beijing, so I went there. I decided I
like him then, so I went, but lots of people aren't willing to cross that threshold because
of difficult realities. I have a friend who also came to Beijing this way, but ended up
breaking up with her boyfriend. Everyone's life is different, everyone has different ways
of thinking, I wasn't going to go talk her out of it or anything. My example is here for
the taking, if she thinks it's a good one, it's her choice, if she considers it poor, giving her
advice is of no use. What if you advise her and she later decides it was no good?

<p><b>Do you have a lot of friends?</b>
<br>Not many in Beijing, but I still keep in touch with all my classmates.

<p><b>If you ever feel sad or depressed, would you confide in friends or in your husband?</b>
<br>In my husband, he is also a very good friend. I usually stifle my true feelings, but he
notices and comes to me, I then tell him what's on my mind. He's not always comforting;
sometimes he scolds me if I've done something wrong. He's quite a rational person, prone
to analyzing my behavior. He's like a pillar of psychological support to me.

<p><b>What do you think of Beijing's atmosphere?</b>
<br>Ha, coming to Beijing was a contrast, I distinctly felt that Beijing was completely
unsuitable for living. In China, Beijing ranks 5th in a list of the 10 most livable cities, I
though that was rather gloomy, what a list, huh? Beijing isn't as livable as my hometown.
<p>Also, maybe it's because I'm a Southerner that I find Beijing so unsuitable. The pressure
in Beijing is immense, you go and come from work on crowded subways, it's upsetting.
There are too many people, this life is truly only for lack of a better option.

<p><b>Did any foreigners strike up conversations with you here [in Kassel]?</b>
<br>Yes, but I had no way to communicate. Today I came across someone from the Catholic
Church handing out pamphlets; maybe they had something to do with religion. This
person spoke to me in Chinese then gave me a pamphlet. He could say a few sentences
in Chinese, but he couldn't speak English. Other people have tried to talk to me, but not
all that many. Maybe they're used to it, this exhibition is held every five years, they have
already encountered all kinds of skin colors and nationalities, it's not strange to them. The
world keeps getting smaller and more homogenous every day.

