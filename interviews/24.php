<b>受访者24。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;： 出版社网编，女，1980后，湖南人</b> 

<p><b>能讲讲你工作三年来的经历吗？</b>
<br>三年换了两三份工作。我是学财务的，前两份工作与专业有关。在北京财务工作不那么好转，就找了一家软件公司做工程项目助理。做了一段时间以后想换个环境，就在出版社找了一份工作，做网编，也想往这方面发展。

<p><b>你身边的朋友有没有和你类似经历的转行做与自己专业不相干的工作的？</b>
<br>有啊，很多，有人做过市场调查。在大学不光是学专业，也是学一个学习的方法，培养能力。说现在很多大学生做的工作都与所学的专业无关，这种现象也不能用好或不好来形容。当然有一部分人是迫于生存压力或者社会压力，可能因为找不到与自己专业有关的工作，所以放弃去做别的。也可能是刚从学校出来的时候心比较高，后来发现想从事的工作做不了，就降低心态，做一份比较基层的工作。还有的人呢，工作了一段时间之后发现自己兴趣不在这边，所以转行业很自然。总的来说，有人是迫于压力被动选择，有人是出于兴趣主动选择。

<p><b>你是因为压力还是兴趣所在？</b>
<br>我是因为兴趣所在。

<p><b>来这里以后有没有与你预期不同的地方？</b>
<br>最开始我以为是组织这么多人，又发相同的衣服，可能是要搞什么活动，类似于行为艺术的某种表达方式。但是来了以后，就是让我们自己参观，到处看一看玩一玩，没有集体地去表现什么主题，这一点让我很意外。本来我觉得是我作为其中一员去表现&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;的某个想法，也很好，但他什么都不要我们表现，只要自己参与。我觉得这种方式挺好的。

<p><b>你有没有看展览上的作品？</b>
<br>我现在看得还比较少。昨天早上轮到我刷碗，我就等到刷完碗以后才出去的。在外面看了看卡塞尔的环境，感受了一下这里的氛围，看了看格林兄弟博物馆。回来的路上看了教堂里面的一个作品，很多纸箱子堆出来的一个造型，我也不清楚那是什么。里面黑漆漆的，有一个屏幕，里面有一个人在弹钢琴。今天去看了城堡，里面多是一些古典的画。说实话，可能我对这方面不是特别了解，看了那些古典的画还是觉得不太明白，看现代派的作品也不是很能理解，可能有一个面或者一个线条想表现什么东西，但不是很清楚。

<p><b>你现在是单身还是已婚？</b>
<br>这个很有意思。我报名的时候还是未婚，入选以后我结婚了。我们是上学的时候一块玩认识的。现在领了结婚证，但还没有去办婚礼，也还没有在家里办酒什么的。对于这个活动，我的参与过程很短，但我的恋爱过程并不短。2月底报名参加《童话》，3月8号办的结婚证，3月中下旬接到通知说我被选上了。我记得说3月20日之前会发出所有通知邮件，我是19日才收到的。

<p><b>你觉得现在人有没有重男轻女的思想？</b>
<br>有啊。我一个同学的同事，生了两个女儿，后来他们离婚了。在广东的山区里，男方家里特别重男轻女，那个男的自己也很严重。生了女孩以后，南方的父母不肯来照顾小孩，小女孩见到他们，叫他们，他们都不理会，好像生了女孩就跟仇人似的。我还看过一个新闻，一个女的生了女孩，家里不高兴，她就发疯了，直接在医院把孩子从楼上摔下去了。这种情况虽然越来越少了，但还是存在，在福建和广东特别是山区农村，很多人还有这样的想法。

<p><b>以后经济条件、各方面条件成熟的话，你希望要一个还是两个孩子？</b>
<br>希望越多越好。我最近在看连续剧《家有儿女》，宋丹丹演的。他们是二婚组成的一个家庭，男方有一个大女儿和一个小儿子，女方也有一个儿子，他们组成一个家庭，很幸福很温馨。这当然有点脱离现实。

<p><b>你是自己来北京开创新天地的？</b>
<br>我是一个人来的。我男朋友在北京读书，我就过来了。当时就觉得喜欢他，就来了，但是很多人会因为现实困难而不肯突破这个坎。我有个朋友也是这样来的北京，但后来就跟男朋友分开了。每个人的生活不一样，想法不一样，我也不会去劝她开导她什么的。我的例子就在这儿，她如果觉得好，自己会选择，如果觉得不好，你劝她也没有用。你劝了她，到时候她觉得不好了怎么办？

<p><b>你朋友多吗？</b>
<br>在北京的不是很多，但和原来的同学都还保持着联系。

<p><b>如果你遇到不开心的或者压抑的事情，你会找朋友倾诉还是和老公说？</b>
<br>我会跟老公说，我老公也是我一个很好的朋友。心里话我一般都憋着，然后他看出来了，就会找我，我就说出来了。他也不是安慰，有时候会骂我，如果我做的不对的话。他是比较理智的人，会分析我的行为。他可以算是我精神上的支柱。

<p><b>你觉得北京的环境怎么样？</b>
<br>呵呵，来到北京一对比，明显感觉到北京是多么不适合居住。在国内，十大最适合居住的城市，北京排在前五名，我看了都觉得郁闷，这叫什么排名啊？北京还不如我老家适合生活。也可能因为我是南方人，来到北方不太适应。北京的生存压力、社会压力都太大了，上下班挤公交地铁我就很有感触。人太多，生活特别无奈。

<p><b>这边（指卡塞尔）有跟你打招呼的外国人吗？</b>
<br>有，但是我无法跟他们沟通。昨天我碰到天主教的人，发一些小册子，可能是关于教会的一些东西。那个人用中文问我好，然后说送给我。他也就会说这么几句中文，也不会说英语。其他人也有主动跟我打招呼说话的，但不算很多。可能他们已经习以为常了，这个展览每5年就会举办一次，他们接触过各种肤色、各种国籍的人，不稀奇了。地球越来越小，相互之间越来越融合。

