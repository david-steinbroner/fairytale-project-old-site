<b>受访者4。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;：大学教师，男，1970后，湖北人</b>

<p><b>你怎么看你作为1001个人中的一个来了这里？</b>
<br>我觉得特别高兴。能出国对中国人来说太不容易了，非常不容易。我都没想到能出国，能到欧洲太好了。今天上午我感到非常兴奋。首先，欧洲的城市、生活比较舒服，生活悠闲，生活质量好，环境也好。在国内挣个钱，我感觉很累。在国内有些紧张、焦虑，在这儿完全放松了。这两天有人供我住、供我吃，挺好的。其实，展览并不是让我很兴奋，还不如我一下飞机看这里的生活环境，我觉得那更兴奋。他们欧洲人怎么生活，这个挺新鲜的。

<p><b>你怎么看&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;的这次行为？</b>
<br>这是他的作品，估计他还是想说明一些问题，觉得他的艺术和政治锲在一起。过去的艺术作品好像都是很具体，画张画啊，做个装置啊，都是对物的，对人特别少。本来艺术就是通过一些中介、媒介给人感受，比如通过一个画让别人感动，他现在直接用人，特别好。

<p><b>他的作品怎么和政治联系？</b>
<br>首先，说起经济问题，这么多人要过来，这钱哪来？首先&nbsp;&nbsp;&nbsp;先生怎么得到钱？我们怎么没钱？这是个问题（插话：他得到了国外的资金）。就是嘛，他有关系，这关系就是政治。本来人与人的关系就是政治，他能跟那些人碰到一起。

<p><b>你喜欢他吗？你喜欢他还是喜欢他的艺术品？</b>
<br>我挺喜欢他！我和他接触过，他这人一方面能让人感到非常真诚，好像挺近的，但实际上距离特别遥远，他和你在一起的时候，能让你感到很放松，这很不简单。我第一次和他见面，他和你握手，头一点，眼睛一眨……觉得很放松，很近，不像你来了以后拿这个炮筒（指麦克风）对着我。

<p><b>你是教书的，你有没有种误人子弟的感觉啊？</b>
<br>我还好，我会尽我的所能去讲。比如说在讲艺术概论课、理论课的时候，我会不用学校制订的教材，我会把教材放在一边，会跟同学说这个教材我不喜欢。我会跟他们讲像&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;啊，我接触到这样一个人，他干什么。这样的信息，这个信息都是很直接的，是我看到或者是我听到的，教材上面不可能讲到。

<p><b>你在教书的时候觉得你的学生缺少某种价值观或者信仰么？</b>
<br>学生就是小孩，爸爸妈妈养着他们。我有许多学生就不愿意学这个专业，是家里逼着的。有个别是比较感兴趣，他们就和玩得我比较多一些，我们一起也拍过片，像一些广告。


