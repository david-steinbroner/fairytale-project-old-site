<b>Interview 4: &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;：college teacher, male, born in 1970s, Hubei</b>
	
	
<p><b>How do feel about coming here as one of the 1001 people?</b>
<br>I am quite happy. It’s very, very difficult for Chinese to go abroad. I never thought of being able to go abroad and being in Europe is fascinating. I am very excited this morning because, first of all, life in Europe is comfortable, relaxing and of good quality. The environment is nice too. To make a living in China is very exhausting and I always feel nervous and anxious at home. But in here I am completely relaxed. It’s nice that I can live and eat for free these days. As a matter of fact I am not very excited about the exhibition. When I got off the plane I just wanted to check out how do the Europeans live. That’s more exciting for me.

<p><b>What do you think of &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;’s act?</b>
<br>I guess he wants to make a point and his art has something to do with politics. In the past art was more concrete, like a painting or a design, it was about things and not people. Any way, art is supposed to bring people feelings through certain media, like a painting, and this time he directly uses people to make art. I think it’s great.

<p><b>How does his work related to politics?</b>
<br>Economically speaking, it costs a lot to bring so many people here. How can Mr. &nbsp;&nbsp;&nbsp; get the money and how come we can’t? This is the question (he has international funding support). He has connection and connection means politics. Politics is all about connection between people in the first place, and he has this connection.

<p><b>Do you like him? Do you like his personality or his work?</b>
<br>I like him very much! I came into contact with him once and he impressed me as being sincere. When we were together it’s like we were extremely close, but in fact it’s not, and this made me feel relaxed. The first time we met we shook hands and he nodded and winked, made me feel relaxed and close. Not like you holding a gun (microphone) at me.

<p><b>As a teacher, do you feel you are misleading your students?</b>
<br>I am not bad. I just do my best to teach them. For example, when teaching lessons like art theory I never use official text books. I told my students I don’t like the text books and I told them people like &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; and the things he has done. Such immediate information is what I saw or heard and you can’t find such information on books.

<p><b>Do you feel your students lack values or beliefs?</b>
<br>Students are kids. They are still being raised by their parents. Many of my students don’t like this major and are forced by their parents to learn it. Some are interested in it, and they spend more time with me. We have done short movies together, like commercials.


