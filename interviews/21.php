<b>Interview 21: &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;: guitar player in a band, male, born in 1970s, from Tianshui in Gansu.</b>

<p><b>This is your first time out of the country, right? Did you play a show in Kassel?</b>
<br>Yes. We didn't preform, it was more like a get-together. Everyone got together on the
last day in the place where we were staying, some foreigners where there too, it was just for fun. &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; (the other guitar player) said that until that day, we had never played
this many songs together. We played over 60 songs, all to accompany people; everyone
sang no matter what we played, everyone sang to popular songs, they even sang to the
Internationale.

<p><b>In the art fair itself, did any works impress you?</b>
<br>There was a piece by a performance artist, whose name I don't remember, who hung
up a pile of clothes. Two girls interacted with the piece, they might have been dancers,
they struck different poses, sometimes climbing the pile and hanging upside-down. I
didn't quite understand what the piece was trying to express, I don't really understand
these things. The whole exhibition [Documenta] was like this, some pieces made me feel
something, but it's hard to concretely express what. Some pieces I didn't get at all, maybe
it's because I don't really understand art, and if it were music I’d be more at ease.

<p><b>Did you see &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;'s chairs and "Template"?</b>
<br>I saw "Template" after it fell down. I think it was an accident, but after it fell it was also
really good, it became another work of art. Art goes both ways.

<p><b>Did you have any expectations before coming to Kassel?</b>
<br>I didn’t have any expectations at all. It's the opposite of going to a familiar place, like
going somewhere to preform. I might still understand and try to imagine what it'll be like.
But no matter how I imagine a foreign place like Kassel, it will never turn out like it was
in my imagination, once I left I wasn't worried. Our band's lead singer said, "here's a free
opportunity to leave the country and go see the world, I think it'll be great." Germany
is even more open－minded that I had imagined, there were lots of unexpected
rewards. I think maybe "Fairytale” is meant to make a difference in every participant’s
life, by changing his or her mind and thoughts a little.

<p><b>Do you like rock music?</b>
<br>Of course I like it, if I didn't like it I wouldn't play it, the only thing I don't like about it is
that it doesn't make much money these days. I do it purely out of love. I listened to rock
growing up, then I became a musician. We always say we've might've been tricked, I
used to dream of becoming a rock star, but that's impossible nowadays.

<p><b>Do you still believe in your dreams?</b>
<br>Actually, my dreams were destroyed long ago when I had to start focusing on tangible
gains.

<p><b>Do you travel often?</b>
<br>I really like to travel, when my finances allow it, I just go, always on my own, with no
purpose in mind. First I look for a convenient hotel, then I figure out how to save money,
then I go have a good time. Travelling in China these days always like a rip-off, when
you're buying things in Kassel, it doesn't feel like they're ripping you off, even though
their things are really expensive, I really feel at ease, it's really different.

<p><b>What are your views on money?</b>
<br>I think poverty stunts ambition, because if you're really poor, even if you're full of
ambition and aspiration, you have no means to realize your dreams. Only after you've
established a sturdy financial base can your imagination really soar, you can imagine all
sorts of extraordinary things.

<p><b>What has given you the greatest sense of accomplishment to date?</b>
<br>The biggest accomplishment without a doubt comes from playing in the band &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;.  A lot
of people like our songs, this is probably what most musicians wish for, but on top of
that, this moment also fulfills me. Compared to other things, I'm really rather suited to
making music.

<p><b>Do you have expectations for the future?</b>
<br>I used to have a lot, now I have rather few. Before, I would stake everything on one bet,
nowadays it seems I've learned to live with both hands so one hand can make money
while the other hand enjoys life. More and more I've come to realize that if you don't
enjoy life, things become very empty.

<p><b>What do you think about love?</b>
<br>Love really is possible, I kind of believe in love. I think love is a complex thing, lots of
things aren't simple; no one can explain it clearly. There's sex, there's also feelings, there
are lots of complicated things in love. Sex is rather primitive, love is cerebral. Sex is a
craving, like hunger, you must satisfy it when it comes over you, you can't resist it, you
can only control it.

<p><b>Do you feel sex, creation and art are intimately related?</b>
<br>I think sex is reflected in many things. For instance, why do we like McDonald's?
Really, it's because there's something sexual about it, it's like horomones. Rock'n'roll also
expresses a type of male energy, sexual energy, and that's what makes girls and everyone
like it. I feel like sex itself is art, and art is a way of expressing sex, maybe not always
with nudity but by using other ways to express sexual feelings.

<p><b>How do you get along with your parents?</b>
<br>Our family is pretty open-minded and democratic, they never were hard on me, they supported me doing what I liked to do, this definitely had a huge influence on me.

<p><b>Do you have faith?</b>
<br>Basically, no. Maybe I have too many doubts about most things, I think it's a good thing
that some people are spiritual, but I have doubts about any religion, I think religion is just
a philosophy of idealism, a way to conduct yourself in society, if you're Buddhist, you
consider everyone to be good and honest. So I always have these doubts, but I never set
out to smash doctrines, I just consider religion as a code of conduct. I think Confucius’s
principles have a deep-rooted influence in our thought system, you don't need religious
beliefs to have a system of values and thought.

<p><b>Are there things you revere in life?</b>
<br>It's hard to explain, maybe I’m afraid to. Maybe politics.

<p><b>When you're filling out a form - nationality, ethnicity, occupation, region... do you
approve and identify with these statuses that society imposes?</b>
<br>Even if you don't, they will still be there. You consider yourself to have your own
identity, but the outside world still influences you. It's like some people consider artists
to have a certain attitude, but maybe it isn't really so, or some think musicians are a bit
lazy, but you may not consider yourself that way, you think your job is really serious.

<p><b>If you had the chance, would you want to stay in Kassel?</b>
<br>I would like to, but I haven't thought about what I'd do here if I stayed.

<p><b>What Chinese characteristics do you think you posses?</b>
<br>I think a lot of things about me are very Chinese, especially my way of expressing
emotions, that's very Chinese.

<p><b>Do you feel inferior compared to the West?</b>
<br>I don't.

<p><b>Do you have an understanding of traditional Chinese culture?</b>
<br>A little seeped in, but my interest in it really isn't that great. I feel like a lot of China's
good things come from the people; a lot of good things still haven't been brought to light.
Mainstream things are definitely not that good, really good things, all things valuable, are
still among the people. Like now on TV, there's some really awful folk musicians, but
maybe one day I'll hear a truly great folk musician, maybe the music will be great.

