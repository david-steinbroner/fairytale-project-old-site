<b>受访者21。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;（&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;）：乐队吉他手，男，1970后，甘肃天水人</b> 

<p><b>你是第一次出国吧？你们在卡塞尔演出了吗？</b>
<br>是。那不算演出，算是联欢，。就在我们住的地方，跟大家一起联欢，是最后一天，也有一些外国人，主要就是自娱自乐。那天李维岩（另外一个吉他手）还说呢，我们俩从来没有在一起配合演奏这么多首歌。我们弹了60多首歌，就是完全跟别人伴奏，弹什么他们都唱，所有的流行歌都唱，连国际歌都唱了。

<p><b>对展览本身有没有什么印象深刻的作品？</b>
<br>有一个行为艺术的作品，我不记得名字了，挂了一堆衣服，两个女孩穿插在其间，她们可能是舞蹈演员，摆出不同的姿势，有时候挂在顶上，有时候倒挂着。我不太清楚这是想表达什么，我不太懂这些东西。整个展览也是这样，对那些作品，能感觉到一些什么，但具体要说也说不清楚。有些作品就是完全看不懂，因为不了解这一方面，如果是音乐的话可能会好一点。

<p><b>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;那些椅子和那个《门》，你看了吗？</b>
<br>我们看《门》的时候，它已经倒了。我觉得就像一个意外一样，倒了也挺好，就变成另外一个艺术作品。艺术有两面性。

<p><b>你去卡塞尔之前有没有一些期待啊？</b>
<br>没有期待，完全没有期待。相对来说去一个比较熟悉的地方，比如说去外地演出，我还会有一些期待，因为我会了解，我会想象。但是对国外卡塞尔，怎么想象也不会和我想的一样，我去了之后特别平静。当时是我们乐队的主唱告诉我的，能有一个免费出国的机会，去见见世面，我觉得挺好的。德国比我想象的还要开放，有不少意外收获。我觉得可能《童话》的意义就在于每个参加这个活动的人他生活上或多或少都会有一些改变，脑子、思想上的改变。

<p><b>你喜欢摇滚乐吗？</b>
<br>肯定是喜欢，如果不喜欢就不做了，唯一不喜欢的就是它现在赚不到钱。我纯粹是为了喜好，就是喜欢。我是听摇滚乐长大，然后做乐手。我们老说可能是被骗了，我过去的梦想是成为摇滚明星，现在看来不可能。

<p><b>你还相信你的梦想吗？ </b>
<br>其实梦想早就破灭了，就是想让自己多来一些实惠吧。

<p><b>你经常去旅游吗？</b>
<br>我特别喜欢旅游，只要是经济条件允许的话，我就会去，我都是自己去，完全没有目的性。先找个便宜的旅馆去住，然后怎么去省钱，然后怎么能让自己玩得好。中国现在旅游有时候完全是比较挨宰的感觉，我觉得这次卡塞尔，就是你买东西的时候，你不会有一种挨宰的感觉，哪怕是他们的东西很贵，我也会很放心，这一点我觉得特别不一样。
以前可能只是在中国见到一些外国人，这回去德国，我觉得他们很单纯，很直白，他们是什么样的一个感情，他们就会表达给你，不是特别设防，我觉得这种感觉特别好。

<p><b>你怎样看待金钱呢？ </b>
<br>我觉得人穷志短，如果你真的太穷了，即使你有很多抱负和理想，你也没有办法实现。还是得有一个经济基础以后，你才可以想得特别飞，奇怪的事情都可以去想。现在展不开手脚。

<p><b>你觉得你到目前为止，最大的成就感来自于哪里？</b>
<br>最大的成就感当然就是&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;乐队了。有不少人喜欢我们的歌，这可能是做音乐人最愿意看的，而且最有成就感的也是这个时候。相比其它，我还是比较适合做音乐吧。

<p><b>你对于你的未来有没有期待呢？</b>
<br>以前期待很多，现在期待很少。以前可能特别孤注一掷地做一些事情，现在好象学会了用两只手生活，就是一个手可以抓自己喜欢的东西，另外一只手可以抓生活。我现在越来越感觉到如果把生活丢掉的话，就都是很空的东西。我是一个悲观的人，但也不是特别悲观，相对来说还是积极的吧。

<p><b>你怎么看待爱情呢？</b>
<br>爱情真的会有，我比较相信爱情。我觉得爱情是一个综合体，很多东西不是单纯的东西，没有人能把它说清楚。有性，也有感觉，有很多复杂的东西在里面。性是比较原始的，爱情是脑子的。性就是欲望，跟食欲一样，人必须得有，它来的时候，你是挡不住的，你只能控制住。

<p><b>你觉得性和创作和艺术有没有密切关系？</b>
<br>我觉得很多东西都是性的折射。比如说我们为什么会喜欢麦当娜，其实她就是有一种性的东西在里面，我觉得就像荷尔蒙一样。摇滚乐也是在表现一种雄性的东西，也是一种性，因为表现出来了，所以女孩才会喜欢，所以人才会喜欢这个东西。我觉得性本身就是艺术作品，艺术是性的一种表达方式，可能不是裸体，或者是用一种别的方式来表达出性的感觉。

<p><b>你觉得你和父母的关系怎么样？</b>
<br>我们家可能比较开放，也比较民主，他们一直没有给我施加压力，也支持我做自己喜欢做的事，这点肯定对我影响特别大。

<p><b>你有信仰吗？</b>
<br>基本没有吧。我可能对很多东西怀疑太多了，我觉得那些人有信仰是挺好的一件事，但我对任何的宗教都存有一种怀疑，我觉得宗教可能就是唯心主义哲学，可能就是一种处世观，如果你信佛教，你看什么人都是善良的。所以我老是有这种怀疑，我一直没有打破原则，我觉得它只是一个处世观。我觉得像孔老夫子那些东西对我们脑子的影响是根深蒂固的，你不用信教，可你的价值观念也是这样的。

<p><b>在生活中，你有没有敬畏的东西呢？ </b>
<br>不太好说，威慑倒是可能会有。可能是政治吧。

<p><b>比如说你填一张表格的时候，民族、职业、地域、国家、职业这些，你会不会认同这些社会加给你的身份呢？</b>
<br>你不去认同，它也会是这样的。你好象自己对自己有一个认同，但还有一个外界对你的印象。就像别人会认为搞艺术的人是这样的人，可能不太实在，或者是做音乐的人都会比较懒散，你可能对自己不这样认为，你觉得自己的工作也是很认真的。

<p><b>如果有机会，你愿意留在卡塞尔吗？</b>
<br>愿意，但是我没有想好留在那里干什么。

<p><b>你觉得你身上有什么中国人的特征？</b>
<br>我觉得我身上很多东西都挺中国的，主要是情感的表达方式，还是挺中国的。

<p><b>你觉得你面对西方的时候会不会感到自卑？</b>
<br>不会。

<p><b>你对中国的传统文化了解吗？</b>
<br>有些耳濡目染吧，其实兴趣并不大。我觉得中国很多好的东西，是民间的，很多好东西没有被挖掘出来。主流的东西肯定不是太好吧，真正好的东西还是在民间，真正有价值的东西在民间。就像现在电视上有些民乐演奏，特别难听，可能有一天我会听到一个真正的民乐，它也许会特别好听。


