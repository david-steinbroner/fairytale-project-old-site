<b>Interview 12: &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;: Visual arts student, Shanghai, born in 1980s, Jiangxi</b>

<p><b>What do you think of Visual Communication?</b>
<p>This major is very broad. I think that visual communication has to do with many things and that it is not just two dimensional. I think that it has unlimited possibilities.

<p><b>Is this your first time abroad?</b>
<p>Yes. 

<p><b>This is your first time in a completely new environment. Do you have any thoughts or feelings?</b>
<p>I do! Animals disregard humans, it’s how intriguing! Why is it that when I walk past pigeons, they don’t fly away? And when I passed sparrows, they were jumping around me. Why are there some rabbits in the grass? And when I was by the lake, ducks, and swans in the lake were swimming towards me, so mysterious! Dogs here are really big, but most are tame. 
<p>I’m going to share one thing that really touched me. The first two days were spent in the exhibit, and there was no time for shopping. Today I began to shop. When I was paying in the supermarket, I asked her whether or not she could give me a bag. I assumed that she would pass me two without any thinking, because in China, salesgirls would immediately place your items into a bag. But she said that this must be paid, and the bag was paper instead of plastic. Their environmental sense was so strong. So I thanked her, but did not buy the bag. I put my things into my bag that was very small. Later I used my clothes to pack all the food. I think that in China few people sense this, and would instead ask for plastic bags, as many as possible, which is not good for the environment. 
<p>The afforestation here is great. I like it so much. It is like the countryside in my home, that kind of feeling. I kept walking down the road in the forest park, it is so beautiful there. It is like a labyrinth.  I think there was a diamond advertisement that was shot there. 

<p><b>So you were raised in a wealthy family?</b>
<p>We did alright. I am the only child. My parents love me, but they do not spoil me. I am not from an outstanding environment, but I did not need to worry about foods, clothing, or education. I have a very good relationship with my parents. I had fights with them when I was a child, but no longer when I grew up. 

<p><b>That happened in your adolescence?</b>
<p>Yes, I was always at odds with my mom in the fifth grade in the elementary school. I do not know why my temper was so rude.  But I because another person in the first year of middle school. I began to study hard in the second year of middle sshool.  My grades had since been all right, and this is it for all the following years.

