<b>受访者12。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;：艺术学生，女，1980后，江西人</b>

<br><br><br><b>你所认为的视觉传达是什么？</b>
<br>这个专业很宽泛。我认为其实视觉传达和很多东西联系在一起，不仅仅是一个平面的，我有一种感觉，就是它是很无限的。

<br><br><br><b>你是第一次出国么？</b>
<br>是。

<br><br><br><b>第一次来到这样一个完全新奇的环境，有什么感受？</b>
<br>有的啊。就是动物都不看人，好神奇啊。为什么我从鸽子身边走过，它们都不飞走？我从麻雀身边走过，它们都往我身边跳。为什么草丛里会有兔子？而且我站在湖边看，湖里的鸭子还是天鹅会往我身边游，好神奇啊！而且这边的狗都很大，大部分都很温顺。
<br>先说一个蛮触动我的事情。我前两天一直逛展馆，都没怎么逛街买东西，今天开始去买东西。在超市付钱的时候，就问她能不能给我一个bag，包，我以为她会想都不想就抽两个给我，因为在国内，超市都是直接拿袋子帮你装起来的。当时她说，这个是要付钱的，而且还是纸袋不是塑料袋。他们环保意识真的很强。后来我就说，谢谢，不要了，我自己装在包里面。我带着的那个包特别小，后来就拿衣服把吃的东西都包起来了。我觉得在国内很少会有人意识到这一点，而且还会尽量多地要塑料袋，这样对环保很不好。
<br>这里的绿化很好啊，我好喜欢这里啊。这里很有我们家那边，我们乡下的那种感觉。我从去森林公园的那条路一直走下去，那边太漂亮了，像那个迷宫，我看到的一个钻戒广告好像也是在那里拍的。

<br><br><br><b>那你小时候是生长在一个很优越的环境的了？</b>
<br>还好啦。我是独生子女，虽然我爸爸妈妈很爱我，但他们不溺爱我。我不是那种很优越的环境里长大的小孩，但也是不愁吃、不愁穿，也不愁没学上。我和父母关系很好，小时候吵过架，长大了以后就不了。

<br><br><br><b>那时候是叛逆期？</b>
<br>是。我小学五年级的时候老和我妈妈闹别扭，也不知道为什么那时候脾气很暴躁。上了初一以后就感觉变了一个人似的，初二以后就好好学习了，然后就成绩还好，这么一路过来了。


