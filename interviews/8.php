<b>受访者8。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;：男，小说作家，1970后，北京人</b> 

<p><b>来卡塞尔有什么感想？</b>
<br>我以前对卡塞尔没什么想象，因为我们本身就是&nbsp;&nbsp;&nbsp;老师作品的一部分，但能来到这里参加这个活动还是挺好的。没来之前，这个城市还有点神秘感，来了之后神秘感消除了，觉得和我想象的差不多。卡塞尔跟中国的一些小城市有点像。天气有点像大理，阴晴不定。城市的感觉有点像内陆的小城市，安阳一类的，没什么起伏，没什么波澜。我也看到过一些吵架的，类似于开车的和行人发生争执，但我也不知道他们说什么。
<p>我看了那些展览。对于那些艺术家的作品，我没法评价，一方面因为不能全部理解，另外看得也比较潦草，只是一个印象，并且对背景也不太了解，所以很难判断。障碍当然很多，比如语言、文化。我觉得交流障碍是人类普遍存在的问题，即便咱们自己人之间也存在着障碍。

<p><b>可我有时会觉得和一个外国人交流还没有在国内同自己人交流的障碍大。</b>
<br>这可能是因为和外国人交流的内容比较浅，时间也比较短，而在国内交流得比较深。

<p><b>你现在还在写小说么？</b>
<br>我有5、6年没写小说了，但一直在写剧本。最近一年多在梳理以前的一些东西，准备重新开始写作。头两本小说，我自己也感觉不太成功，所以最近五、六年也在研究这个，像哥特小说的历史根源，它们自己独特的艺术规律。

<p><b>你觉得你在创作中是否有比较严重的焦虑感？它源自于什么？是怎么表现的？</b>
<br>有。会担心自己写不好。主要是一再告诫自己要甘于边缘，同时每一个艺术家又都希望自己的作品被大众接受，这可能就是焦虑的根源。

<p><b>你现在对你的生活满意么？</b>
<br>满意。我现在每天写三千字。不过，以这种速度写作，才刚写了一年。写作对我来说是比较理想的生活。现在还写得出来，愿意每天呆在家里写。除了写字我也干不了别的，何况整天在家呆着还能少花点钱。
<p>我是个书呆子。我的生活就是大量读书。从前读书是瞎读，30岁以后，发现自己好多书还都没读过，于是就从经典的读起……比较绝望的就是要读很多，而且也不知道是不是读完之后就会豁然开朗或下笔如有神之类的。

<p><b>你觉得中国在这个世界的位置是孤立的，还是真的像大家所说“全球化”了？</b>
<br>我写的作品不是只分析中国人，写男人，写女人，我在写作的时候没想到我是中国人……之前，我没接触过欧洲人，也没接触过美国人，所以也不知道……我就是一个中国人，我也没法做一个“世界人”，但也没必要自卑。

<p><b>你觉得中国人有信仰么？</b>
<br>应该有吧。什么是信仰，我也不太清楚。没法回答。可能每个人定义不一样，有人觉得自己有某种信仰，但信基督教的人可能会觉得这个不是信仰。一个会说中国话的德国人努力向我宣传过基督教，他认为世界上有很多宗教，但其它宗教信仰的都是人，只有基督教信仰的是神。

<p><b>你比较喜欢哪些西方艺术家？</b>
<br>法国十九世纪的作家如巴尔扎克，还有托斯妥耶夫斯基……

<p><b>托斯妥耶夫斯基给我印象最深刻的，是他最充沛的感情完全是心灵上自我拷问式的自我矛盾、自我揭露。他挺怪的，挺脏的，但是那种东西还特别纯洁，还有宗教信仰。</b>
<br>对。

<p><b>你觉得中国小说和西方一流小说有差距么？</b>
<br>我觉得差距很大。当然，我们可能基础差一些，尤其是有些作家不能代表中国，他们自己有自己很高的文学业内的地位。我觉得西方文学圈看待中国作家，也和当初中国看待苏联作家差不多，有一些独到之处，比如说高行健吧，国内人接触得很少。我本人也觉得他不是很好。

<p><b>作为一个男人，你觉得怎么样才能算是成功？</b>
<br>我的想法和社会上的想法差不多，就是你要有一个稳定的职业，一个固定的收入，收入在评价线以上，大概2、3倍以上吧。但我个人没有成功的概念，因为我觉得每个人都是失败者⋯⋯我曾经和一些朋友一起喝酒，如大仙他们，后来喝怕了。

<p><b>你认同他们这种生活方式么？从主流的价值观看，是有一点颓废。</b>
<br>我还是认同的。每种生活方式，只要自己希望，又不危害社会，就挺好的。我以前跟过他们喝酒，后来觉得每天喝酒是有一点浪费时间。主要是有一阵我结婚了，世俗压力比较大，每天要写书、写剧本，很忙，喝多了酒就会影响工作。后来，我又离婚了，就又出来喝酒了，觉得这种生活方式挺好的。

<p><b>你的婚姻经历会不会让你的爱情有挫折感？</b>
<br>没有。因为我觉得离婚对我来说确实是一种解脱。可能我理解的爱情和大众不大一样，我觉得两个人从一而终、天长地久是骗人的。我理解的爱情是互相都感觉很好，没有太多负面的东西。我觉得婚姻只能算各种爱情里面的一种。

<p><b>那你觉得爱情是有期限的，不是长期的？</b>
<br>这毫无疑问。爱情开始的时候很值得怀念，但后面漫长的过程是很平庸的。而且，爱情的寿命不可能和人的寿命一样长，因为人要尝试不同种类的东西，所以爱情的寿命可能会更短些。

<p><b>可是我觉得大部分女性会和你持不同观点。</b>
<br>那是因为她们是弱势群体，需要从一而终，需要安全感。

<p><b>也许你不能对一个女性保持长久的感情。那假设你很喜欢小说，你怎么保持对它长久的兴趣和激情呢？</b>
<br>这确实需要自我调整。我有过厌倦的时期，在那两年写剧本的时候，我有过不想再写书的想法。我觉得走出了文学圈，有很多人根本都不看书，但这也不影响他们的生活和他们对世界的判断，这让我觉得写小说没有意义，无法对别人的生活进行真正的介入，充其量只是一种娱乐方式。可是调整了一下，还是觉得愿意写。

<p><b>那你对爱情还会有期待和向往么？</b>
<br>当然会有。

<p><b>有些人只有性冲动。</b>
<br>我曾经也有过，觉得其他人都对我构不成吸引力了，只有这个人，以后就过日子了。但是理智和情感不大一样，有些是属于肉体范畴的，不受你的理智控制。包括性欲，我觉得它也是情感的一部分，对某个人有性欲，我觉得也挺好的。

<p><b>可是男性这种性冲动发生的概率永远高于爱情发生的概率。</b>
<br>对。如果要把它们分开来看，是这样的吧，要不怎么说爱情难得、珍贵呢。

<p><b>我听一些女性朋友说，如果你要和一个超过40岁以上的中国男人发生爱情，真诚地对待爱情，那几乎就是一件与虎谋皮的事情。</b>
<br>我想是这样的。

<p><b>你还没有超过40岁，你对爱情还有期待是因为这个？</b>
<br>爱情还是我创作的主要动力。我记得好像是渡边淳一说的一句话吧，他七十了，自认为还没有走过青春。有的人30岁可能就有了40岁的心态，不同的心态吧，这是一个怎么在这个世界上存在的问题，是愿意过年轻人的生活，还是愿意过中老年的生活。我毕竟也奔40了，看得比较开，对所得和所失都能看得开了。我没有太多困惑。

<p><b>你觉得自己有什么缺点？</b>
<br>我比较懒惰。

<p><b>你认为自己有什么优点？</b>
<br>诚实。

<p><b>你认为生活可以没有艺术吗？</b>
<br>生活不可以没有艺术。荷尔德林说，人要诗意地居住。只有艺术才能抵达诗意。

<p><b>艺术能改变这个世界吗？</b>
<br>能。坚信能够。

<p><b>艺术能让人生好一点吗？</b>
<br>答案是肯定的。	

<p><b>你对中国当代艺术有什么印象？</b>
<br>中国当代的艺术家都在忙碌着，他们的作品在寂寞着。

<p><b>你最喜欢的艺术作品是什么？</b>
<br>凡高的《向日葵》。

<p><b>你有梦想吗？</b>
<br>有。没有梦想的生活不堪想象。

<p><b>你嘲笑过有梦想的人吗？</b>
<br>从不。我对他们从来是肃然起敬。

<p><b>你认为人为什么会有梦想？</b>
<br>人有超越自我不断上路的本能。

<p><b>梦想对一个人有什么作用？</b>
<br>让人活得更快乐。

<p><b>没有梦想的人生是什么样的？</b>
<br>行尸走肉。

<p><b>没有梦想的国家是什么样的？</b>
<br>乏味无趣，死气沉沉。

<p><b>你身边的中国人信仰什么？</b>
<br>努力工作，照顾好自己的家庭子女，安分守已过日子。



