<b>Interview 8: &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;： male, novel writer, born in 1970s, Beijing</b>

<p><b>How do you feel about coming to Kassel?</b>
<br>I had no ideas of Kassel before. We are all part of Mr &nbsp;&nbsp;&nbsp;’s work any way. But it’s good to be here. I was very curious about this city before I came but I am not now. I feel it’s pretty much the same as I expected. Kassel is similar with those small towns in China. The changeable weather is like Dali. It feels like an inland small city like Anyang, quiet and calm. I have seen people fighting over traffic problems but I don’t understand what they were saying
<p>I have seen those works in the exhibition, but I can’t comment about them because I don’t fully understand. Besides I watched pretty carelessly without familiarity of the background. There are a lot of barriers such as language and culture. I think communication problem is very normal among people, even within us Chinese.

<p><b>But sometimes I feel less hindered talking with foreigners than with Chinese.</b>
<br>Maybe it’s because communication with foreigners is relatively shallow and short, while with compatriots the communication is deeper.

<p><b>Are you still writing novels?</b>
<br>I didn’t write novels for 5, 6 years. I write scripts now. This year I have been going over the things I wrote and preparing to write novels again. I feel unsuccessful about my first two novels so I have been working on it for 5, 6 years. For example, I am studying the historical origin of Goth novels. They have their own laws.

<p><b>Do you feel seriously anxious when you are composing? What’s it origin and how does it express itself?</b>
<br>Yes. I am worried about the quality of my work. It’s mainly because although I keep telling myself that I should be prepared of being marginalized, on the other hand, every artist wants his work to be accepted by majority. Maybe this is the origin of the anxiety.

<p><b>Are you satisfied with your life now?</b>
<br>Yes. Now I write 3,000 words everyday. Writing is the ideal life for me. I like writing everyday at home when I still have something to write about. In fact I can’t do anything else except writing. Besides, staying at home all the time saves me money too.
<p>I am a bookworm. My life is reading. I read randomly before 30, after that I found there are so many books that I haven’t read. So I began to read those classical works. It’s a depressing thing that there are too many books to read, but you don’t know when you finish them whether or not things will just click into place or you will be full of inspirations. 

<p><b>Do you think China is in an isolated position in this world or do you believe, like everyone says, that China is “globalized”?</b>
<br>I don’t just write about Chinese. I write about men and women, and I never think of myself as a Chinese when I am writing. I haven’t gotten into contact with any Europeans or Americans before so I really don’t know… I am just a Chinese. I can’t be a world-citizen. But there’s no need to feel shameful or uncomfortable about it. 

<p><b>Do you think Chinese have faith?</b>
<br>I guess they do. I am not quite clear about what constitutes faith so I can’t answer for sure. Maybe it’s up to everyone. Some might think they have a kind of faith but Christians might feel that it is not faith at all. Once, there’s a German Christian tried to convert me. He spoke in Chinese painfully. According to him there are many religions in the world, but everyone else believes in man except Christians because they alone believe in God.

<p><b>Which western artists do you like?</b>
<br>The 19th century French writer Balzac and Dostoyevsky…

<p><b>What Dostoyevsky impressed me most deeply is that, his emotions are totally from spiritual self torment and self exposure. His works are strange and kind of filthy. But they are also pure and religious.</b>
<br>Yes, it is.

<p><b>Do you think Chinese novels are behind western novels?</b>
<br>Yes, far behind. Maybe we have inferior groundwork. I think some of the Chinese writers can’t represent China but they hold high places in the literature circle. I guess western people see Chinese literature in the exact way as we see Former Soviet Union literature. We found it has something special. Like Gao Xing Jian, Chinese readers are not familiar with him. I myself don’t think he is very good, either.

<p><b>As a man, what do you think is success?</b>
<br>My idea is pretty much the same as the society. A stable job, a regular income, maybe 2 or 3 times higher than average. But personally I don’t feel successful. I think everyone is loser. I used to drink with some friends, like Da Xian, but not anymore. It’s horrible.

<p><b>Do you approve this kind of lifestyle? From the mainstream view it’s decadent.</b>
<br>I think I do. You can live as you like. Every lifestyle, as long as it doesn’t damage society, is good. I used to drink with them, later I felt it wasted too much time to drink everyday. And then I got married and there’s life pressure. I had to write books and scripts everyday. I became too busy to drink because drinking would affect my work. But afterwards I got divorced and I began to drink again. I think it’s nice to live this way.

<p><b>Does your marriage experience make you feel frustrated about love?</b>
<br>No, because divorce for me is a relief. Maybe I understand love differently from most people. I think it’s a lie to say “together forever”. Love for me is just about feeling right mutually. Marriage is just one kind of love.

<p><b>So you think love is short-lived, not long term?</b>
<br>Yes, definitely. When love begins it’s fascinating. But after that it’s just a long and dull process. Besides, love can’t last as long as people because people need to try different things. So I guess love is short-lived.

<p><b>But I think most females won’t agree with you.</b>
<br>This is because they are weak and need to feel secure.

<p><b>Maybe you can’t maintain your passion for a woman for a long time. But you like novels, what makes you keep a long term interest and passion for that?</b>
<br>It needs self-adjust indeed. I have moments of weariness. At the time when I wrote scripts, I used to think that I would never write again. I said to myself that outside the literature circle there are many people who don’t read at all, but this does not affect their lives and their judgments. This makes me feel that writing is pointless… I can’t really influence people’s lives and writing is at best a way of entertainment. But when I calm down and after the self-adjustment I find myself still want to write.

<p><b>Do you still expect and long for love?</b>
<br>Of course I do.

<p><b>Some people just have sex impulse.</b>
<br>I used to have love, feeling that others wouldn’t attract me anymore and she is the one and we just live together from now on. But emotion is different from reason. There are certain things that belong to your body and are not controlled by your reason, such as desire. For me desire is part of emotion. It’s actually a good thing to be sexually attracted by someone.

<p><b>But men tend to produce this kind of sex impulse far more frequently than falling in love.</b>
<br>It’s right, if you have to distinguish these two things. This is why people say love is rear and precious.

<p><b>Some female friends told me that if you want to fall in love with a man over 40 sincerely, it’s almost like borrowing the skin from a tiger.</b>
<br>I think so.

<p><b>Is it because you are not over 40 yet that you still expect love?</b>
<br>Love is my greatest motivation of writing. I remember it was Junichi Watanabe that said, although he was 70, he though himself still in his adolescence. But some people are over 40 inside when they are just 30. Different mentalities, that’s all. It’s a question about how to live in this world, to live a young life or an old one. After all, I am about to be 40 too, and I have an open mind about what I lose and what I get. I am not confused about life.

<p><b>What kind of women do you like?</b>
<br>It’s hard to say. Sometime I like fat women sometimes I like slim women. There are lots of features that sometimes can’t be embodied by a single person. Well, I have a big appetite. 

<p><b>What defect do you think you have?</b>
<br>I am lazy.

<p><b>What virtue do you think you have?</b>
<br>Honest.

<p><b>Do you think you can live without art?</b>
<br>Life can’t go without art. Holderlin said man should dwell poetically. Only art can dwell poetically.

<p><b>Can art change this world?</b>
<br>Yes, I believe it firmly.

<p><b>Can art make life better?</b>
<br>The answer is affirmative.

<p><b>What’s your impression about Chinese modern art?</b>
<br>Chinese modern artists are busy but their works are lonely.
	
<p><b>What’s your favorite work of art?</b>
<br>It must be Sunflowers by Van Gogh.

<p><b>Do you have dream?</b>
<br>Yes. Life is intolerable without dreams.

<p><b>Have you ever mocked people with dreams?</b>
<br>Never, I always respect them.

<p><b>Why do you think that people have dreams?</b>
<br>Humans have the instinct to transcend themselves.

<p><b>What can dreams do to people?</b>
<br>They make them happier.

<p><b>What about people without dreams?</b>
<br>They are like zombies.

<p><b>What is a country like if it has no dream?</b>
<br>It would be boring and lifeless.

<p><b>What do the Chinese people around you believe in?</b>
<br>Working hard, taking care of their wives and children and living their lives honestly and with satisfaction.


