<b>受访者20。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;（&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;）：艺术家，男，1970后，甘肃人</b> 

<p><b> 你是做什么的？</b>
<br>在家里简单画点画。我在北京的生活就是一年四季画画。租个房子，暂时也不卖画。我是藏民，从小是在青海的拉卜楞寺旁长大的，那个地方还是一个比较保守比较偏远的地方。

<p><b>你这次来德国有没有期待？</b>
<br>没有，没什么期待。就觉得好玩。你做自己的事，你期待某某大艺术家干吗？也没有必要期待某某策展人。

<p><b>你每天关心的问题是什么？</b>
<br>我自己。

<p><b>你不关心比如说能源问题、，教育问题、战争啊这种大事？</b>
<br>可能会浏览一下吧，但确实不是很关心。

<p><b>你平时话也不多，是吧？</b>
<br>嗯。

<p><b>你有信仰么？</b>
<br>信仰？知识就是信仰。

<p><b>你认为自己是一个理性的人么？</b>
<br>我在往这方面努力。大家信的释迦摩尼啊、默罕默德啊、耶稣啊，他们都是理性的。

<p><b>信宗教么？</b>
<br>会浏览一些，比如说我们的藏传佛教。

<p><b>对艺术来讲，最重要的是什么？</b>
<br>它有寿命。一种知识。艺术是自慰品。

<p><b>那你最喜欢的是什么？是画画吗？</b>
<br>我对这个东西慢慢失去耐心。画画没什么意义，因为没有秘密。表达观念，只是这样。公共题材。

<p><b>你最喜欢的故事是什么？</b>
<br>没有。

<p><b>你小时候不听故事的么？</b>
<br>小时候听。都忘了，没有动听的故事。

<p><b>你平常看不看《新闻联播》？</b>
<br>偶尔会看。

<p><b>但其实你并不关心，是吧？</b>
<br>对。

<p><b>你觉得你自己是个自私的人么？因为我想你可能更关心自己的内心世界。当然，这两个点并没有联系。</b>
<br>这个跟自私没关系。就算你这个人不存在，这个世界仍然会按照它的规则不停地运转。这是我对生活的态度，一个方式，对现实的一种对抗。面对生活，我很少努力。我觉得我面对现实的时候，比较虚无。平时喜欢乱想很大的问题，而且常被这些问题想得焦头烂额。

<p><b>你在绘画上是个技术主义者么？</b>
<br>作为一个艺术家，面对绘画，只有你的想法，而不是考虑到技法。我比较喜欢情绪抽象的。

<p><b>其实我觉得你还是一个很擅长抽象思维的画家。</b>
<br>因为自己一个人呆惯了，难免相对傻一些。我朋友不多，很多人我都不喜欢。平时和朋友聊天不多，难免相对傻一些。

<p><b>你怎么看待爱情和性？</b>
<br>肯定有爱情，但我不会去赞美它。关于性的问题呢，老美在６０年代已经做到极致了。人家已经淋漓尽致了，现在我们好多艺术作品还在表现性啊暴力啊歇斯底里啊。我记得有一段时间，画画的人，尤其是年轻的女性特别容易歇斯底里。我觉得真正的歇斯底里也是特别深啊，需要伪装啊扭曲啊，画这个东西也不是完全直观的，也需要抽象化。

<p><b>现在你的工作中最大的困惑和难处是什么？</b>
<br>我最大的困惑就是这个世界变化太快。当你饶有兴趣地画一个画，很快就会出现一个极端的极厌恶的……最后你就会把它剁了拆了扔了。这就是我的痛苦。不停地画是一个负担。解决这种痛苦的唯一的办法就是死亡，没有其它的办法。

<p><b>你信佛么？</b>
<br>我不信佛。我信我自己，但是我觉得肯定会有造物主存在。我对未来没有什么期待，现在死了，我都觉得可以。困惑是什么？一种现实，给你带来压力，然后再让你卷入这种你无法预计无法左右的社会。
<p>我的儿子要出生了。


