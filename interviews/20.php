<b>Interview 20: &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;（&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;）：Artist, Male, born in 1970s in Gansu</b>

<p><b>What do you do?</b>
<br>A home I just paint. In Beijing, year in and year out, my life is only painting. I rent an apartment, for the time being I'm not selling paintings. I'm Tibetan, I grew up in Qinghai in the Labrang monastery - it's a very reserved and remote place.

<p><b>Did you have expectations about this trip to Germany?</b>
<br>No, I didn't have any expectations. Thought it’ d be fun. When you're minding your own business, do you care what so-and-so the artist is up to? There's no use in having expectations about so-and-so's plans.

<p><b>What issues do you care about on daily basis?</b>
<br>Myself.

<p><b>You don't care about major issues like the energy crisis, education, war?</b>
<br>I skim the headlines occasionally, but I really don't care much.

<p><b>You don't usually talk much, right?</b>
<br>Eh. 

<p><b>Are you religious?</b>
<br>Somewhat, I read a little Tibetan Buddhism.

<p><b>When it comes to art, what’ s most important?</b>
<br>That it be long-lasting. A kind of knowledge. Art is masturbatory.

<p><b>What do you enjoy most? Your paintings?</b>
<br>I'm slowly losing patience with them. Painting has no meaning, because painting has no secrets. It’ s really only about expressing concepts. Public subject matters.

<p><b>What's your favorite thing to do?</b>
<br>I don't have any.

<p><b>What stories were you told as a child?</b>
<br>As a kid, I listened. I've forgotten everything; no story was pleasant.

<p><b>Do you watch the evening news?</b>
<br>Occasionally.

<p><b>But you really don't care, right?</b>
<br>Right.

<p><b>Do you consider yourself selfish? I think you might be more preoccupied with your inner world. Of course, these two feelings aren't completely unrelated.</b>
<br>This has nothing to do with being selfish. When a person no longer exists, his inner world can still perpetuate itself according to its own rules. That's my attitude towards life; it's a way to resist reality. I feel a little empty when I face reality. Normally, I like to think about existential questions at random, but I also feel overwrought by them.

<p><b>Is your painting method very technical?</b>
<br>As an artist, it's your way of thinking, not your technique, that's important when facing a painting. I'm more partial to abstract feelings.

<p><b>I really feel like you're an expert abstract thinker.</b>
<br>Since a person gets used to being stupid alone, it's hard to avoid being foolish. I don't have many friends; I don’ t like a lot of people. I don't small talk much with friends; it's hard to not be dumb.

<p><b>What's your opinion of love and sex?</b>
<br>Love certainly exists, but I'm not about to sings its praises. As for sex, it reached its pinnacle in ol' America in the 60s. They've already exhausted all the possibilities; today many artworks still manifest a hysterical obsession with sex and violence. I remember a period when painters, especially young women, were especially prone to hysterics. I think true hysteria is especially dark, it wants to be faked or distorted. Painting this emotion can't be entirely intuitive; it also needs to be abstracted.

<p><b>In your work, what poses the biggest challenge nowadays?</b>
<br>What bewilders me the most is how fast this world is changing. Just when you're engrossed in a painting,an extreme loathing can quickly come over you... then you might destroy it and throw it out. This is very painful for me. To paint incessantly is a burden. The only way to escape this suffering is through death, there is no other solution.

<p><b>Are you Buddhist?</b>
<br>I'm not Buddhist. I believe in myself, but I believe a creator exists. I don't have any expectations for the future. I could die now. Everything is possible. What is confusion? It's a reality, a reality that pressures you and implicates you in an unpredictable and incomprehensible society.
<p>I'm expecting a son.

