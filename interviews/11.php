<b>受访者11。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;：舞蹈演员、家庭主妇，女，1970后，北京人</b> 
<br><br><br><b>你是做什么工作的？</b>
<br>我以前是跳舞的，现在不跳了，现在当全职妈妈。我小孩该今年上小学了。我27岁结的婚，老公比我大13岁。

<br><br><br><b>比你大这么多，会有交流上的问题吗？</b>
<br>我老公是艺术家，没有问题。

<br><br><br><b>你相信爱情么？你是怎么看爱情的？</b>
<br>我相信有真爱。爱情跟家庭是两回事，不是说有了爱情就没家庭，或有了家庭没爱情。爱情和家庭是相辅相成的，你有了爱情以后，你再有了家庭，你们两个人目标一致，方向一致，努力的愿望一致，这样可能更有意义一些吧。

<br><br><br><b>在你的生活里除了感情和家庭之外，还有什么有意义的东西？</b>
<br>还有什么有意义的东西？看到我儿子每天快乐，自己忙忙碌碌的。我的成就感就是我的儿子。我觉得幸福就是每一天你自己去体会，悲也好，喜也好，生气也好，吵架也好，不管所发生的一切是不是对你的爱，对整个带来很多想象不到的东西。

<br><br><br><b>因为家庭放弃舞蹈你不觉得可惜吗？</b>
<br>我不觉得可惜。我没有放弃舞蹈，那是中学的事。大学我没有学舞蹈，那时学的是戏剧表演，也不算是表演，是那种配音。我没有觉得放弃。我毕业以后也干了类似相关的工作，但真正接触以后，我觉得好像自己做这个事情不是那么游刃有余，还是有一些抵触的东西在里面。那会儿也可能年轻，简单一些。但我现在并没有后悔。现在，结婚以后，有了小孩以后，也一直在做事，杂志社呀，包装乐队啊，“二手玫瑰”前期的企划是我做的，那会儿我跟&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;一起做企划，后来，他们的第一盘专辑上市后我就不做了。我做的每一件事都是蛮有趣的，都是我喜欢做的事才去做。比如我当老师、教课，都是自己喜欢做的事，而且也是没有任何委屈或者什么的，就是喜欢就去做，不喜欢了，觉得辛苦了那就停下来，调整一下，因为人是需要调整的，不能说一味地就是工作。

<br><br><br><b>你怎么教育孩子？</b>
<br>我们那一代都是很传统的那种教育，上课的时候手背在后面，认真听讲，不许做小动作，我觉得这种东西特别束缚小孩。你本来是一个特别有好奇心的小孩，老师这样的话往往是用这种规则的东西限制你，你就会觉得越来越没有意思。像我儿子，现在我们就不要求他，因为他现在还在上幼儿园大班，我就不要求他，我就觉得应该随便怎么样好了。

<br><br><br><b>作为一个艺术家的妻子，你眼中的艺术家是什么样子的？</b>
<br>我眼中的艺术家，活生生的一个人。艺术家很单纯的，想什么就直接地表示，没有那么复杂，很单纯。反正我老公是挺单纯的，我不知道别人是什么样，我老公挺单纯，挺率性，很直接。可能我们俩的方式就是这样，特别直接，没有夹杂着很多东西，但是这个中间也需要一个磨合，你需要顺着他，适应他这种思维方式，慢慢就好了。

<br><br><br><b>你怎么看1001个人来德国？</b>
<br>我觉得这个作品挺好的。童话，每个人都是童话的一部分，有的人有了这种童话的想法不见得能实现， &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;就实现了，所以是一个特别好的事。

