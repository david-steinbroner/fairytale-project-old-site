<b>Interview 11:&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;: Dancer and housewife, female, born in 1970s, Beijing</b>

<p><b>What do you do?</b>
<p>I used to be a dancer, but no longer. Now I am a housewife and mom. My child is going to elementary school this year. I was married at the age of 27, and my husband is 13 years older than me.

<p><b>He is so much older than you, are there any communication problems?</b>
<p>My husband is an artist, and there are no problems at all.

<p><b>Do you believe in love? How do you perceive love?</b>
<p>I believe in true love.  Love and family are two matters, which does not mean that once you have love you lose your family; or once you have family you lose love. Love and family are complementary.  Once you have love, and then you have a family, and the two of you share the same target, direction, and willingness to work, it probably is more meaningful.

<p><b>In addition to the feelings of your life and family, what are some other meaningful things?</b>
<p>Anything else meaningful? I am happy every day when seeing my son, and I am very occupied. My son is my acheivement. I think that to be happy you have to feel everyday, sad or joyful, angry or quarrelsome. No matter what happens it could be related to your love or not, and a lot of unexpected things happen.

<p><b>Do you feel at all that it was a pity that you gave up dancing to have a family?</b>
<p>No, I do not. I did not give up dancing, it was something I did in middle school. I did not study dancing in the college. I was studying theater performance, but it wasn’t really performance, it was dubbing. I do not feel that I gave up. After graduation, I did similar jobs, but I did not feel that I was talented enough for this career. There were some inner conflicts. That was when I was young, and simple-minded. But I do not regret it now.  After being married and having children, I keep working, in magazines, and bands. I did the early planning of Second-hand Rose when I was doing corporate planning with &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;. But I stopped doing it when Second-hand Rose released their first CD.  Everything I have done is interesting, and I only work on things that interest me. For example, I became a teacher because I enjoy teaching. I do not want to be pressured to work on things. If I like it, I will do it, but if it becomes tiresome, I will stop, or make changes. People need to be able to make changes to their life and not let their jobs dictate it. 

<p><b>How do you educate your children?</b>
<p>My generation received a very traditional education. In the classroom, our hands were behind our backs, we listened attentively, and were not allowed to fidget. I feel that this is extremely restrictive to children’s growth. Children are naturally curious and playful, but teachers used these tactics to restrain you, and you become bored. As for my son, we have no such requirements because he is in a preschool. I think it’s fine that what happens, happens.

<p><b>As an artist's wife, what does an artist look like in your eyes?</b>
<p>An artist in my eye, is alive. An artist is very pure, and will express their thoughts directly. Anyway, my husband is very pure. I do not know other artists, but my husband is very forthright and direct. Maybe that is our way, very straightforward, and we try not to worry about trivial matters. But there is a process of mutual adjustment, you have to follow his way, get used to his logic, and gradually it will be fine.

<p><b>How do you see the visit of 1001 people to Germany?</b>
<p>I think that the project is great. Everyone is a part of the fairytale. Some people who have dreams may not turn it into reality, but &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; did it, so it is an especially good thing.

