<b>Interview 22: &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;: Visual Arts student, Shanghai, female, born in 1980s, from
Chongqin</b>

<p><b>What are your views on art?</b>
<br>Art is a way to vent your emotions, a means to voice your thoughts, there shouldn't be
any moral restrictions, fundamentally art doesn't serve a purpose, art is very free.

<p><b>Do you think Western and Eastern art differ?</b>
<br>I think they differ considerably, you can see just by looking at their streets and lifestyle.
In the East, everything is very uniform. When you buy a car, the exterior is bare,
whereas it seems almost all Germans decorate their cars. It's the same in cemeteries.
Our cemeteries are monotonous, while their graves all well designed. I feel like they all
understand how to design their lives, every small detail is worth meticulously attention,
they don't choose things thoughtlessly.

<p><b>What do you think of the exhibition?</b>
<br>Some things in the exhibition are all right, some weren't that well done, I rather prefer
interestingly made things. Yesterday I saw an exhibit of masks and faces made from oil
barrels, I thought they were really well done, I was really impressed. There was another
painted piece that from afar looked like lots of things in the distance, but when I got
close, I saw that they were all painted on, I thought that it was really interesting.


<p><b>What's your take on "Fairytale"?</b>
<br>I think &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; is a very thought-driven person, his works reflect his way of thinking, even
if others don't agree, he still goes ahead and does things, it's terrific. No matter what you
say, all of us 1001 people came, there are lots of good and bad aspects, but all in all, it's
a miracle. I think upholding one's vision is very important.

<p><b>Besides art, what other topics do you follow?</b>
<br>Music. I'm interested in lots of things in life, I'm a very curious person, I'll go check out
anything that attracts my attention. But I don't like politics, I barely ever follow politics. 

<p><b>Do you care about environmental issues?</b>
<br>I'd consider so. At the very least, I don't just carelessly throw things away, or pick the flowers on the street. I'm a person of principles, I've cared about the environment since I was little, but you don't necessarily have to go plant trees. 

<p><b>What do you think about nations?</b>
<br>I think it would be best if we didn't need nations, then every race would be the same,
everyone's hair would be the same. Not that everyone's face should be the same, but I
think that no differences in skin color or hair would be best.

<p><b>Why?</b>
<br>I might be a little less interesting that way, but I feel some people might find it easier. I
really don't know, it's just a feeling, I’d like the world to be that way.  

<p><b>How does your generation differ from the preceding one?</b>
<br>Are you referring to our parent's generation or the 70s' generation? Compared to the
70s generation, we have access to a lot more things, like computers, technologies, that
disseminate information faster and easier, we also don't need to look things up in lots of
books to understand things like they did, now we just go online. I feel like my generation
doesn't really like to read, not like before when they said "you have to read to be smart." Now people all watch movies and TV shows.  


<p><b>How do your views on love and sex differ from the previous generation?</b>
<br>Our generation maybe still has a lot of people hoping for long-lasting love, but because
of everyone's busy lives, love has become "fast-foodized," it feels disposable: once
you've eaten, you throw it away, nobody wants to serve the other. I feel like the previous
generation, based on the stories my and his comrades told me, a man would wait for a
woman for however many years, I think these kinds of stories can't happen anymore, I
still haven't come across any, I don't believe anyone waits that long for a girl. 

<p><b>Do love and sex aid creative production?</b>
<br>I think they play a big part in it. I feel like being in love arouses something inside of you, you become a little girl again, naive and childish, thinking the things you make are all really great, you create spontaneously, even if someone else says your work isn't good, you still think it's great.

