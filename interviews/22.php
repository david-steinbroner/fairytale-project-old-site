<b>受访者22。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;（&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;）：艺术学生，女，1980后，重庆人 </b>

<p><b>你怎样看待艺术？</b>
<br>艺术是一种情绪的发泄，是人精神上的表达，不应该存在道德约束，那对于艺术根本不起作用，艺术是很自由的。

<p><b>你觉得东、西方的艺术有差异？</b>
<br>我觉得有相当大的差异，单从他们的街道、他们的生活习性就能看出来。比如中国人所有东西都很统一，买一个车子，上面就是光的，而德国人的车子好像都会自己帖些什么花纹之类的。墓地也是这样。我们那些公墓都是统一的，他们那些墓碑都是设计好的。觉得他们每一个人都很懂得去设计自己的生活，一个小的方面都会去自己精心设计，不会弄来一个什么东西就随便用用。

<p><b>对艺术展有什么感觉？</b>
<br>艺术展上有的东西还是可以的，有些东西做得不是很好，我比较喜欢做得比较有趣的东西。昨天看的展览上有一个用许多汽油桶做的面具、脸谱，我觉得做得很好，给我留下了很深的印象。还有一个画的东西，很远看去，真的像摆了很多东西在那儿，我过去一看，原来是画上去的东西，我觉得很有意思。

<p><b>对《童话》的看法？</b>
<br>我觉得&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;是一个很有想法的人，不说他作品，反正感觉上他是有自己想法的，他认为别人不接受，但还是去做了，这很了不起的。不管怎么说，我们这1001个人过来，有很多不好的和好的方面的消息，他毕竟都做出来了，这就是一个奇迹。我觉得坚持自己的想法，这点很重要。

<p><b>除了艺术，你还关心什么样的话题？</b>
<br>音乐。生活当中很多事情我都很关心，我是一个很好奇的人，什么东西吸引我，我就会去看。但是我不喜欢政治上的事情，我几乎从来不看政治上的东西。

<p><b>那你关心环保么？</b>
<br>我觉得还行。起码我自己基本上不会乱丢东西，或者在街上摘花什么的。我觉得我是有原则的，从小事方面开始做环保吧，不一定要种树啊。

<p><b>你怎么看待国家？</b>
<br>我觉得最好不要有国家，然后所有的人肤色都长得一样，头发都长得一样。不是说脸型一样，是肤色没有差异，头发没有差异，我觉得最好。

<p><b>为什么？</b>
<br>我觉得这样也许会无趣一点，但是这样可能有的人会觉得好受一点。我也不知道，只是自己的感觉吧，我希望世界是这个样子。

<p><b>你们这一代人和上一代人有什么差别？</b>
<br>你是指父母辈还是指70年代？和70年代比，我们比他们接触的东西更多，比如电子化、数码的产品，接触的那些信息又快又方便，也不用像他们那一辈人要看很多书才能了解到很多东西，现在上网方便了。我感觉现在的人不是很喜欢阅读，不像以前说“心灵需要阅读”，感觉现在的人都去看电影、电视剧了。

<p><b>你觉得你们这一代人在爱情、性上和上一代有差异么？</b>
<br>我们这一代可能很多人希望有一个长久的爱情，但因为各方面的事情，爱情变得“快餐化”了，有吃了之后就赶快扔掉的感觉，来得快去得也快，谁也不愿意为谁服务。我觉得上一辈，比如我爸爸给我讲他的战友，那个男的等了那个女的多少多少年，我觉得这种故事现在不可能发生了，我还没有遇到过，等待一个女人等那么长时间，我不相信。

<p><b>爱情、性对创作有帮助么？</b>
<br>起的作用很大的。我觉得一个人恋爱，会激发内心的一种状态，感觉自己又变成一个小女生了，童真、孩子气又出来了，感觉自己做的东西都特别棒，不管做什么，一件作品即使别人说不好，自己也会觉得很棒。


