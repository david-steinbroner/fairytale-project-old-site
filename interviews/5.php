<b>受访者5。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;：&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp，女，1980后，江西景德镇人</b>

<p><b>你怎么看1001个人来卡塞尔这件事情？</b>
<br>我觉得这个数字听上去蛮壮观的，如果只是一两个人来的话，可能没有特别大的意义，而1000多个人来就会发生意想不到的事情。这整个工程也是挺浩大的，很辛苦。我很喜欢0和1这两个数字，我的幸运数字是11。

<p><b>那你是怎样知道《童话》征选人员的呢？</b>
<br>我挺喜欢看别人的博客，订阅了很多比较关注的博客，自动更新了，我就看到了。

<p><b>你觉得这个展览怎么样？</b>
<br>我觉得最好能有人带着我们看一下。不过我们在这种游历的状态里看这些作品，是不是同时也在被人观察，我就不知道了。在国内也经常看一些展览，有现代艺术的，也有传统一些的。怎么说呢？国内的即使是大展，像在中国美术馆的，也就是一两天热闹一下，开幕式人是最多的，后面就没什么人来了。而这里呢，看展的有很小的孩子，各种各样的人都有，而且开了已经有一个月了吧，还是有这么多人，这里的氛围我觉得真的是很好。但从作品来说还没有给我一种触动感，比预期的稍差一点点。

<p><b>之前你对德国有什么印象？和来了之后的感觉有差别吗？</b>
<br>德国有很多电器。之前觉得德国人应该是挺严谨的，这次来到这里，感觉很温馨，这里的人都主动地帮助别人，主动跟人打招呼。这次我最得意的就是有了这个手环，太爽了。吃住什么的也都挺满意的，有一点像大学那种感觉。

<p><b>你觉得这次参加《童话》对你来说最有意义的是什么？</b>
<br>我觉得这次很值得纪念。虽然我也在全国各地到处走，但真正融入一个作品中还是第一次，很新奇的一件事情。每天都觉得时间很紧张，想要多看一点，再多看一点，只能睡三个小时。大家都差不多。

<p><b>听说你办签证的时候特别麻烦，能讲讲整个过程是怎么回事吗？</b>
<br>我跑了无数个地方，我的那张纸被盖了无数的章。一大早起来，我先去了我们市的市公安局，之前就知道会非常非常慢，最快也要一个星期，所以就先托人打过电话才过去。之后是区派出所，见到区长给区长呈材料，看了说没有问题，填了表。下一步是到我们厂的派出所，厂派出所的人找我问话，问我要去做什么，为什么要出去，我回答完后所长给我盖了一个章。之后我又去了社区的居委会，找居委会大妈，之后再去厂派出所盖一个章。</br>
<br><br>完了回到区派出所，区派出所要开一个当地人证明，我爸给我开了一个。对方说我爸不行，必须是非直系亲属，只好再到办公楼去拉了一个人做证明。证明要给区长签字，区长不在，出去开会了，便找了个熟人托他打车拿着我那个文件去找区长，区长在开会的间隙帮我签了字。好，签完了字，我拿着我填好的表格去市公安局交掉，这时候他们告诉我说还漏了一个章，已经下午5点多了，而他们5点半就关门了，我只好又去厂派出所。他们告诉我这个表格不用我自己再去交了，他们来就好了。</br>
<br><br>我是办得最快的了，说两个星期以后就可以拿了。我爸两个星期之后过去拿，却被告知要再开一个交了100多块钱的证明。我们之前不知道这一点，因为是厂派出所的人办的嘛，就这样又折腾了一回。从我们家去一趟南昌要两个半小时，我觉得我参加《童话》之前的心力都在那个地方被耗尽了。</br>
<br><br>过了好久，突然接到电话通知我说马上就要去了，我觉得劲都已经使完了，累得不行了。不过人来了，还是挺好的。在&nbsp;&nbsp;&nbsp;老师的博客上看到不同的图片、照片，都是很直观的。

<p><b>你是学什么专业的？平时工作感觉怎么样？</b>
<br>我在艺术圈老跟人家说我是学设计的，他们都以为我是学平面设计的，其实我学的是飞行器设计。 [。。。] 不过从一开始我就确定绝对不会从事这个专业，因为动力设计实在是太恶心了，要做三道大题，做出半道来就能过，可是我一道都看不懂，太难太难了。我原来在广告公司工作，现在是在网站做市场，相对以前算轻松的吧，不过我觉得是工作都很累。

<p><b>[。。。]，学了以后不从事本专业，你不觉得可惜吗？</b>
<br>我觉得大学就是培养思考的方式。教育是一个方面的问题，还有一个方面是家庭。我爸爸是搞航空的，高中文理分科的时候我想学文，但他帮我报了理科。后来考大学，他帮我填的志愿，我不在家，等我回来已经报完了，自己没有选择。我家里人比较传统。但我觉得大学出来以后，自己的路还是应该自己去把握。大学里最难的还是考试，我最害怕的就是考试，非常非常难，我讨厌死了。

<p><b>除了艺术，你还关心什么？</b>
<br>我比较关注地方市民的一些变化。我蛮喜欢看新闻的，就是很小又很有趣很怪异的一些事情，我不太喜欢看大的新闻。

<p><b>你怎么看中国的艺术圈？</b>
<br>我不是很喜欢“圈子”这个词。怎么说呢？鱼龙混杂吧。有些人莫名其妙，但有些人还是很好的，我能感觉得到他们内心的真诚，他们的内心比外表还要更朴实一些，会让我很感动。当你能够真正坐下来跟他们聊的时候，他们会天南海北地跟你聊，无所不聊，就是那种胡扯八扯的感觉，那种感觉我还是蛮喜欢的。我觉得真正的艺术是生活化的，我不是很喜欢纯艺术，我喜欢那种艺术应用在生活中的，比如一些家居类的小设计，他们的想法很奇妙，让我感觉很不错，而且对我也很有帮助。

<p><b>你觉得我们对传统文化的继承多吗？</b>
<br>我觉得我们应该还是在传统里面的，其实传统里面也是很多好的东西，比如水墨。但我们的心态又很浮躁，总想摆脱传统，觉得这样才是好的。

<p><b>浮躁的原因是什么呢？是因为缺乏信仰吗？</b>
<br>我觉得有宗教信仰是一件好事情，但这并不是全部的原因。可能是因为我们现在进入了一个快速发展的阶段，有很多不平衡吧。一方面我们看到了外面的东西，觉得有很多东西很好很好，另一方面我们又意识到与西方还是有一定的距离。我们没有静下心来好好想一想这个距离是需要有一个过程才能赶上的，就想一下子跨过去。

<p><b>你是江西景德镇的，景德镇还有传统的东西在吗？</b>
<br>有，比如说烧瓷的技艺，有一些陶瓷学院的学生会继承下这些东西，但生活上的东西就没有什么了，人们往往渴望现代化的东西。陶瓷方面的大师也是要考级的，跟钢琴一样要考级，不同等级的人办的展览也不一样。陶瓷学院的学生有的做得真的是超级好，很棒很棒，他们会不停地考级。要成为一个大师，就要经过无数次的考级。

