<b>Interview 5: &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;：female,  born in 1980s, Jingde town, Jiangsu</b>

<p><b>What’s your opinion about the event that 1001 people coming to Kassel?</b>
<br>The number is magnificent. If there are just a few, it can’t be this meaningful. But with more than a thousand people anything can happen. It’s a big project and it’s toilsome to accomplish. I also like the number 1 and 0. 11 is my lucky number.

<p><b>How did you know that <i>Fairytale<i> were selecting people?</b>
<br>I like to read other people’s blog and I booked several blogs. I saw it when the blog renewed.

<p><b>How do you feel about this exhibition?</b>
<br>I think it would be better if someone could guide us through the exhibition. However, because we are tourists, I don’t know whether or not we are being watched at the same time when we are watching those works of art. I often attend exhibitions in China too, modern art as well as traditional art. Well, in China, exhibitions never last more than two or three days, even those big ones such as in the Chinese Art Gallery. The opening ceremony is most exciting, but few people come afterwards. Here, however, viewers include all kinds of people, even small children. It has been a month and there are still so many people. The atmosphere is perfect. As to works, I am not touched. It’s not as good as I expect.

<p><b>What’s your impression about Germany before? Do you feel differently after you come here?</b>
<br>There are many electronic products in Germany. I thought Germans are very rigorous but when I come here I feel sweet. People here are helpful and warmhearted. It’s wonderful that I have this wristband. Food and room are satisfactory too. It feels like I am in college again.

<p><b>What’s the most meaningful thing for you to join <i>Fairytale?<i></b>
<br>I think it’s memorable. Although I have been traveling around China, but this is the first time that I really integrate myself into the art. It’s a wonderful thing. Everyday I feel the time flying and I just want to see more. I only sleep for three hours, so does everyone else.

<p><b>I heard you’ve been through a lot of troubles with your visa, could you tell me the whole thing?</b>
<br>I have been to endless places and my paper has been stamped for numerous times. I knew in advance that it would be very slow so I called before I went and got up very early and went to the city public safety department. The next was the district police station, I submitted my material to the chief, he checked and I had to fill in a form. The next was the police station of our factory. They called me and asked me why did I want to go abroad and what for. After that there’s another stamp and I had to see the old lady responsible for the neighborhood committee of our community. Then there’s another stamp from the factory.
<p>When this was done I went back to the district police station and was told to show a testimonial from a local people. My father wrote one for me but they said it must be none-relative. So I had to go to the office building to find someone. The testimonial needs to be signed by the district chief but he was out at a meeting that day. So I asked someone to call a taxi and bring my document to the chief and he signed it in the break of the meeting. After this was done I finally went back to the city public safety department to submit my form only to be told that there was one more stamp left. But it was past 5:00 pm and they all closed at 5:00. I had no choice but to go back to the police station and they told me I didn’t have to submit the form myself and they could do it for me.</b>
<br><br>It turns out that I am the fastest. It only takes two weeks. My father went to take the visa but was asked to show a receipt of 100 yuan. We didn’t know this because it was the factory police station that took care of it. Therefore we had to go through one more trouble. It takes two and a half hour from my home to Nanchang. I feel my energy was exhausted before I went to <i>Fairytale<i>.

<p><b>What’s your major in college? How do you feel at work?</b>
<br>In the art circle I always tell people I majored in design. They all think I majored in Graphic Artist Designer but in fact I majored in Aerocraft Design. [...] But from the very beginning I already knew that I wouldn’t make it my career because dynamic design is extremely difficult. In the final exam we have to complete three questions but I don’t understand any of them. It’s too hard. I worked in a commercial company before and now I do marketing for a website. Relatively it was easier before, but I guess any work is hard.

<p><b>[...] Don’t you feel pity not doing what you have learnt?</b>
<br>I think university is the place that fosters your way of thinking. Education is just one side of the problem and I have to consider my family too. My father does aerocraft. When it’s time to choose humanity or science in high school I wanted to learn humanity but my father made me choose science. As to the college entrance exam he filled the application form for me. My family is quite traditional and I don’t have any choice. But after graduation, I think I should take control of my life and choose my own road. I was afraid of exams and I hated them. They were too hard.

<p><b>What else do you care about besides art?</b>
<br>I care about the ordinary things happening to local townsfolk. I like watch news a lot, I mean those little, funny and weird things. I don’t like big news.

<p><b>How do you feel about the art circle in China?</b>
<br>I don’t like the word “circle” very much. Well I think it’s good and bad mixed up. Some are just without rhyme or reason but others are not bad. I can feel the sincerity in their heart. They are simpler inside than they appear to be and this touches me. When you sit down and talk with them they will talk about everything and I like this feeling. I think the real art is for our life. I don’t like “pure art”. I like art applied in life such as small designs of furniture. Some of their ideas are interesting and inspiring to me.

<p><b>Do you feel that we inherited a lot from traditional culture?</b>
<br>I think we are still within our tradition. There are many good things about tradition, such as ink and wash painting. But we are always flippancy, always trying to get rid of tradition, thinking that would be better for us.

<p><b>What’s the reason for this flippancy? Is it because the lack of religious belief?</b>
<br>I think it’s a good thing to have belief, but lack of belief is not the only reason. Maybe it’s because we are in the phrase of rapid development and there is a lot of imbalance. On the one hand we knew about the world outside and discovered many good things, on the other hand we felt the distance between us and the west. We never have the patience to realize that it takes time to remove this distance but always want to get there at one blow. 

<p><b>You are from Jingde town. Is there still traditional stuff in Jingde town?</b>
<br>Yes there is, such as the art of making Pottery. Students in the pottery school will hand down this tradition. But life is different, most people just want modernization. You have to take many tests before you can be a pottery master, just like piano. There are also exhibitions of different levels. Some of the students in the pottery school are doing really, really well. They will keep taking numerous tests to become masters.  

