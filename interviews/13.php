<b>受访者13。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;：艺术学生，女，1980后，江苏无锡人</b>

<p><b>你为什么学习艺术？</b>
<br>学艺术是因为我对艺术非常热爱。在高中本来我是喜欢物理化学，高二的时候临时转学艺术。从小艺术就是我的特别爱好，小时候父母怕影响我学习，不让我画画，但到后来，我发现自己对艺术的追求越来越强烈，我就跟他们说，即使让我选择这种理工科的东西，四年出来，我还是会转到艺术。

<p><b>你怎么看卡塞尔和文献展？</b>
<br>可能因为卡塞尔这个城市人口比上海少很多，他们绿化方面比我们做得好很多。这里的城乡差异不明显，即使是城里人也有自己的田地，和我们不一样。我沿路过来，看到墙上有很多涂鸦，我感觉中国什么时候能这样，中国的艺术就会上升很多。

<p>艺术展有些作品非常有创意，比如那个把很多壶放在墙面上的作品，像人脸一样。我自己的艺术修养不够，加上大部分是德语，所以有一些作品看不懂，很费解。我觉得&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;先生的作品应该是卡塞尔文献展上很重要的一个，巧合的是，&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;先生和大自然合作了一件作品——那个门虽然倒下来，但是我觉得它比以前更具有生命力。

<p><b>你怎么看国家这个概念？</b>
<br>以前课本上怎么说国家，我不太记得了，但我觉得作为一个中国人，在国外，我们的一言一行不仅代表了个人，而且代表整个国家，代表了中国。中国是比较传统的国家，不像西方人那么开放。像西方人有什么“性文化”，中国人就比较保守，不会把这种主题运用到自己的作品上去。

<p><b>你比较关注生活中的哪些问题？</b>
<br>我是一个非常自信的人，对未来的看法比较积极。我认为年轻的时候应该把全部精力放在学习上，不仅仅是知识上的学习，还有学做人，这是非常关键的。首先要学好做人，才能学好别的东西。我最近在网上看到很多虐待小动物的事情，有些画面触目惊心，不仅是“虐猫事件”，还是活剥狸猫、活宰牛，极度残忍。人类可能为了一些奢侈的享受，比如裘皮大衣，做出这么残忍的事情，我觉得不仅仅需要反省，而且需要尽量杜绝这种现象。

<p><b>你怎么看待宗教信仰？</b>
<br>艺术就是我的信仰和追求。我觉得宗教和信仰是两个概念，宗教通常是指佛教、基督教啊之类的，信仰在各个精神层面上都可以体现，不仅仅是宗教，艺术也可以算一种信仰。

<p><b>你和家长交流有什么障碍吗？</b>
<br>我的家长很开明，像朋友一样对待我，我有什么事情都会跟家长说，交流没问题，我也想不出有什么困惑。

