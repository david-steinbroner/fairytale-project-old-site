<b>Interview 13. &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;, Visual arts student, Shanghai, born in 1980s, Wuxi, Jiangsu province.</b>
 
<p><b>Why do you study art?</b>
<br>I study art because  I love it very much. In high school I liked physics and chemistry, but I transferred to study art in the second year of high school. I have been fond of art since my childhood, but my parents did not allow me to paint as they were afraid that my studies would be influenced. As time passed, I found that my desire to pursue art became stronger and stronger, and then I told them, I would transfer myself into art after the requisite four years in college if I am forced to study science or engineering.
 
<p><b>What do you think about Kassel and Documenta?</b>
<br>Probably because the population in Kassel is much smaller than that in Shanghai, the local environment of works have been done far better than us. The differences between rural-urban seems not evident, and even urban residents hold their own fields, unlike us.  I saw a lot of graffitis on the wall along the road I took, and I feel that Chinese art would be much improved if this happens in China.

<p>Some works in the art exhibition are very creative, for example, the work that attached many kettles to the wall. It looked like the face of human being. I do not have much art background, and because most works are in German,  there are some works that are difficult to understand.  I think that Mr. &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;’s work is one of the most important in the exhibition.  Coincidently, Mr. &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; and Nature co-designed a work- Although the door fell down, I feel that it demonstrates greater vitality than it did previously.


<p><b>How do you see the concept of countries?</b>
<br>I do not remember what the textbooks talked about before countries.  But as a Chinese abroad, each of our works and activities represents not only ourselves, but our country, China. China is a country relatively conservative, not so open as Western people. For example, there is the "sex culture" in the West, but Chinese people are comparatively conservative, and would not make this kind of theme in their works.

<p><b>What kind of questions usually draws your attention?</b>
<br>I am a very confident person, and relatively optimistic for the future. I think that when I am young, all my energy should be devoted to study, not only knowledge but also how to conduct oneself.  This is very crucial. First of all it is to conduct oneself, and only after this can we learn other things. I recently learned of a lot of pet abuse from looking on the internet. Some scenes are really horrible. They not only abused cats, but also skinned  leopard cats, and killed buffalos, so brutal. Human beings have done so many brutal things for their luxurious consumption, such as fur coats. I think that what we need is not only to reflect but also try to put an end to this phenomenon.


<p><b>How do you perceive religious faith?</b>
<br>Art is my faith and pursuit. I think that religion and faith are two concepts. Religion usually refers to Buddhism, Christianity, etc, while faith could be expressed through all levels of spiritual existence. In addition to religion, art can be counted as a faith.

<p><b>Do you have any communication problems with your parents?</b>
<br>My parents are open-minded, and treat me as a friend. I tell them anything I like, we have  no communication problems. I cannot think of any confusion.

