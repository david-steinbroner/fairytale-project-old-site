<b>Interview 26: &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;: Photography editor and photojournalist at a regional industry newspaper, female, born in 1970s in Liaoning.</b> 

<p><b>How did you come to participate in "Fairytale"?</b>
<p>I'm a photojournalist and photography editor myself. Actually, it's very difficult to take a vacation or go
on holiday in our office, but our chief editor really loves art, he said this project was very interesting, he
knows of &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;, he knows of his father,&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;. He said, go ahead, take 10 days off. I often read
teacher &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;'s blog*, I more frequently read his
interviews with journalists. I like his tone of voice. If teacher says he did something, then it can't
have been unsuccessful, and if he didn't do it, how could it have succeeded? In any event, his voice really
speaks to me. The day I saw Fairytale on his blog, I left a comment saying Fairytale was very compelling,
because it foretold of many impossible things that would occur. When I typed "F" on teacher &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;'s blog,
it didn't matter if I typed the character for "fly" or the English, it all meant the same thing. Really, when I
stepped aboard the plane and we all flew together, I felt this fairytale had come true. In fact, I was a reserve
candidate, because when saw the blog post, it was already the last day to register. They had those one
hundred questions, I answered them as fast as I could, in an hour, because I was scared I wouldn't make the
deadline. At the end there was one question asking, "What is an artist?" I answered an artist is a person who
makes other people experience something extraordinary. Art is praiseworthy for rousing emotions in each
person's heart, it more or less represents sentiments.

<p><b>What is your personal life like? Does art play a big part in it?</b>
<p>I'm a photojournalist at &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;, I'm also the photo editor. I handle 50 photographs
everyday, approximately 200 pictures a week, I process them in Photoshop, sometimes I also do some other
similar things. I often go to art exhibitions, like the ones at the Central Academy and so on. I'm particularly
interested in contemporary performance art, I sometimes feel that performance art permeates people's lives
more deeply, it's a more real and more direct way of expressing things. A painting or photograph can have a
big visual impact on people, but performance art leads to deeper reflection.

<p><b>How to you feel about the installation "Template" collapsing?</b>
<p>It fell very naturally, nature raises a question, and it doesn’t mean it’s up to us to assign a meaning or that
teacher intended it to collapse when he built it. What happened was an act of nature. It stood, then
it collapsed, what we see after the collapse is that it still exists, it didn't end, or stop being successful in the
fall.

<p><b>You've worked in news for decades now, are there difficulties working in the media in China?</b>
<p>There certainly are, but I don't encounter them since I work as a journalist in a professional niche. Industry
media records the positive and ignores the negative because it needs to report elating and constantly
improving news. For example, when you work in this trade, you report on the most outstanding communist
party members, you report about how these people motivate even more people, then you talk about how
the industry continues to do remarkably well. Maybe it's corrupt. I personally consider the news' essence to
be truth. Some things aren't untrue, rather, some things really can't be broadcast, these things that can't be
broadcast really aren't unreasonable or anything. That's how I see it.

<p>
*Translator's note: interviewee refers to the artist as "teacher"

