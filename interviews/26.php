<b>受访者26。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;： 辽河油田辽河石油报社摄影部图片编辑，女，1970后，辽宁人</b> 

<p><b>你是怎么参加《童话》这个活动的？</b>
<br>我自己是做摄影记者和图片编辑的。实际上我们单位以前很难请个假或放假，但我们总编特爱艺术，说这个事情挺有意思，他知道&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;，也知道他爸爸&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;。他就说，你去吧，十天时间。
<br><br>我常看&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;老师的博客，更多地是看他和记者的访谈，我喜欢他语言的那个调子。比如 &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;老师说什么事做了，就没有不成功的，不做怎么会成功呢？反正他的那种说法我特别能接受。那天我在博客上看到《童话》，就在上里面留言，说《童话》挺有吸引力，因为这个预示着很多不可能的事情发生。当时我在 &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;老师的博客里说“F”，无论是汉语拼音“飞”，还是英文“fly”，都是飞翔的意思。实际上踏上这趟飞机，飞机一起飞的时候，我就觉得这个童话实现了。
<br><br>其实当时我是候补的，因为那天已经是报名的最后一天了。他们有那一百道题，我回答可快了，一个小时，因为害怕不赶趟。最后有一个问题，问什么是艺术家，我回答说艺术家就是让人平常的生活出情绪的人，艺术可贵在让每一个人心中萌发出一种想法，或多或少地代表一种感受。

<p><b>你的个人生活是怎样的？艺术在你生活中占的比重大么？</b>
<br>我是辽河石油报的摄影记者，也是图片编辑。我每天有五十个图片要处理，每个星期大约有二百多个图片，就是做Photoshop的处理，有时候也做一些相关的培训。我经常去看画展，像中央美院什么的。我对现代行为艺术特别感兴趣，有时候我觉得行为艺术更渗透到人的生活里，它更现实更直接地表达了一些东西，像绘画、照片可能给人视觉上的冲击挺大，但是行为艺术引发人的是一种深沉的思考。

<p><b>怎么看装置《门》的倒下？</b>
<br>它倒了是很自然的，自然发生的问题，不是我们一定曾经想要赋予它一个什么意义或者&nbsp;&nbsp;&nbsp;&nbsp;老师当初建它时一定希望它倒下来。发生的就是自然的东西。它（指《门》）站过，然后又倒了，倒下来之后我们看到的也是它存在，不是说倒下来了，这个东西就结束了或者就不成功了。

<p><b>你做新闻十几年了，有没有觉得在中国做新闻有难处？</b>
<br>肯定是有的，但是我现在体会不到这个，因为我是企业新闻的记者。企业新闻是扬长避短的，因为企业里需要有一个昂扬向上的东西。比如我们在做企业新闻的时候报道那些优秀的共产党员，报道那些人是为了激励更多的人那样干，然后把企业所有的工作做得更出色更好一些。它可能是个弊端。我自己认为新闻本身的生命是真实，有些不是说不真实，而是有一些真实不能报，这个不能报的东西并不是说它就不合理或者是怎样的。我是这么认为的。

