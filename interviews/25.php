<b>Interview 25. &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; : Documentary film director, male, born in 1970s, Beijing</b>

<p><b>Shooting documentary films seems like a hard thing to do in China.</b>
<br>The documentaries we make wouldn't count for anything if it weren't for foreign film festivals. Within China, there are no standards and no distribution channels, there aren't even any viewing outlets. Once you discover your passion, you study and work so hard to make something. Feedback is extremely important: it means your filmic language and voice gets out there for people hear clearly. I think this exchange is very important, because you don't just make films for your own amusement. In China, since you must create your work on this foundation, in this environment, on one hand you have to admit it influences you, on the other hand you can't be too arrogant. That is your limitation when something in made on this soil.

<p><b>You rarely expose or express your ambition?</b>
<br>I don't have any wild schemes, I've seen too much of that world. Thousands of films, you know where your film stands, it's very clear, too clear. I think it's important to be clear, it's very important to be clear-headed in life. 

<p><b>Does that make you a fatalist?</b>
<br>I know that there's one life, a collective life, that includes the "fifth generation", the "sixth generation", the "seventh generation",* but within this life there are many things you can do. You need to be aware of your limitations.

<p><b>Our reality in China is weird and twisted, right?</b>
<br>Right, there's nothing you can do about it. I consider documentary films and writing to be alike, they both confront problems, there are many subject matters people don't dare address. Documentary films in festivals have more or less the same odds as winning the lottery, there are 2000 films in a festival for people to choose from. In fact, there's a decent amount of documentary films that enter and win awards and prizes. I'm waiting on funds, Korea give me money, I'm on much better terms with them now. Before, I would raise money myself or collaborate with others, that was already working very well. Our people are different from Westerners. Even though the West also has its problems, but there people might get involved with something that apparently doesn't concern them directly. Us, besides professionals, people in Songzhuang**, who will be interested? Very few regular folk are interested. That's why when I shoot a film, I choose to include people who work in, reflect on and participate in the country's public sphere, that's extremely important. 

<p><b>I feel like the Chinese's participation in public life has withered a little, it's somewhat forced.</b>
<br>We can take a look at some of the things I made for the women in rural &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; that shows my personal sentiment on this apathy. I think it's really the cause and symptoms of a disease. The women have been living the same life for so many generations, in the same circle of people, in a dark attic without even any electricity. But they do things with ease and skill, like bats***, they can achieve anything. Even when they cook, you can feel their concentration. It's been that way for so many generations, concentrating on the individual, the private sphere, surviving in that sphere where they squandered their whole life. But as soon as something happens in the public sphere, these women are the first victims. Like here, she has five children [The interviewee points to a &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; woman in the documentary]; maybe not even one will stay by her side. In the Pearl River Delta, wages haven't gone up in years. China has so much cheap labor, everywhere is like this remote place in &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;, like in the central plains of China, like in Henan, how can this be? In the mountains, five children won't come back, who will work in the fields? 

<p><b>Do you think studying Buddhism or converting to another religion still allows one to better understand this world, or are things different now than in the past?</b>
<br>I don't want to talk about things in the past. After reading the Buddhist canon, I may have expressed my views on certain things in my films; my way of looking at people is different. 

<p><b>After shooting for so many years, what do you most want to communicate?</b>
<br>Really, the process of making movies is also an endless process of discovering yourself, creating something that's different from your ordinary life. What's more, once you've shot a great deal it gets very scary, since your fate is intimately related to your work. But at soon as you finish filming, it's all wrapped up, you set it aside and keep moving forward. It's like this process deeply permeates your innermost being, you get to know yourself and human nature. Human nature is often complicated, in the end, we reach a certain complex level, or stumble upon it to some extent. You get to know other people through making movies; you also get to know yourself. 

<p><b>When you look at someone you see their appearance, but in fact you care about their feelings.</b>
<br>Many people who write fiction are also this way, a great imagination can influence reality. After I shoot a film, after you've put yourself in that position, your heart will always hold on to those feelings. Most emotions aren't particularly pleasant, it's not like making movies or contemporary art, there is very little fantasy, everything is extremely real, you can't disseminate grand illusions about people or situations.

<p><b>That's pretty pessimistic way to live.</b>
<br>You recognize the situations you would like to live in, you realize that therein exists life, then when you make something, it's not pessimistic. 

<p><b>So then you've placed yourself in that world by integrating your feelings and your life.</b>
<br>It's always like that before you finish, but once you're done, you have nothing to do with it, you've moved past it. 

<p>* Translator's note: Chinese directors are often classified in 'generations'
<br>** Songzhuang is a large artistic village/community outside of Beijing
<br>*** Bats are very auspicious in Chinese culture, and the word bat is a homonym for good fortune and luck

