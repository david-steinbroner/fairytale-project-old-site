<b>受访者25。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;： 记录片导演，男，1970后，北京人</b> 

<p><b>在国内拍记录片似乎是一件挺艰难的事情。</b>
<br>我们拍记录片的，如果没有国外的电影节的话，我们算什么啊？在国内，没有标准，也没有流通的渠道，甚至连观看的渠道都没有。发现自己这么热爱这个事情，通过自己的努力、学习做了个东西，发现还有反馈，这非常重要，这就说明你的电影语言或者你的声音发出去了，而且别人听见了，听得很清晰。我觉得这样的一种交流非常重要，因为所有的作品不可能是自娱自乐。
在中国这样一个环境，你做的事一定要落实在这个现实的基础之上，一方面你要承认这肯定是非常有意义的事情，一方面你又不要特别狂妄，这就是你的局限性，你是在这样一个土壤里长出来的一个东西

<p><b>你很少表达或暴露你的野心？</b>
<br>我没有什么野心，因为见过的世面太多了。几千个片子，你知道你做的片子在什么位置上，你非常清楚了，太清楚了。我觉得做一个比较清楚的人，对自己的生活能有比较清醒的认识，这很重要。

<p><b>那你岂不是个宿命论者？</b>
<br>我知道有一个命，一个共同的命，包括“第五代”、“第六代”、“第七代”，但我们在这个前提之下可以做非常多的事。你要清楚你的局限性。

<p><b>我们中国的现实、所能看到的东西都比较怪比较扭曲，是么？</b>
<br>对，没办法的。我认为写作和纪录片一样，也面临很多问题，因为有很多题材根本就不敢涉及。记录片在电影节上播放，几率和买“六合彩”差不多，电影节一年2000部，然后从里面选。其实，纪录片进去，获了奖，奖金也没多少。我到现在为止就拿到了一点点资金，韩国给的钱，但这比我以前要好很多。以前都是我自己拿或者和别人合作，这已经是非常好了。
<p>我们的人和西方不一样。虽然西方也有很多问题，但他们的人会去关心看来和他们不相关的东西。像咱们宋庄，除了专业人士，谁会去看？而且去看的便衣还很多。所以我现在做的片子，包括我选择的人、他们做的事情、他们的思考、他们的历程对国家的公众空间是有参与的，这太重要了。

<p><b>我觉得中国人对公共事务的参与是一点点被压抑、一点点萎缩掉的。</b>
<br>你可以看看我给&nbsp;&nbsp;&nbsp;农村妇女拍的那一点点东西，我觉得有我个人的一点感觉。我觉得它其实是一个标本。她们有多少代都是那么生活，生活在自己个人的圈子里，就是一个阁楼里面，黑黑的，以前连电灯都没有。但她们在那里游刃有余，像蝙蝠一样，什么东西都找得到。包括她们在灶台上的一生啊，都能感觉到浓缩。多少代人都一样，非常专注于个人、私人的空间，而能在这个空间里生存下来，就已经把她的整个生命都耗尽了。但是公共空间一旦发生了什么事情，她们全都是牺牲品。就像现在，她［指影片中一&nbsp;&nbsp;&nbsp;妇女；编者注］有5个孩子，可一个孩子都没留在她身边。珠江三角洲，这么多年工资都没有涨上去。中国有这么多廉价的劳动力，像&nbsp;&nbsp;&nbsp;这种偏僻的地方都这样，像中原地区，河南这种地方又能怎么样？在山里，5个孩子都不回来，田谁来种？

<p><b>你觉得读了佛经或者说你皈依之后在理解这个世界的时候是不是和以前不一样了？</b>
<br>所以我不愿意谈以前的东西嘛。我读了佛经后，对一些东西的看法有可能在现在做的片子里实行，看人的眼光会不一样了。

<p><b>那你觉得你拍了这么多年，最想说的是什么？</b>
<br>其实，拍的过程也是不断认识自己的过程，创作和我们平时生活不一样的地方就在这里。而且你拍到一定程度非常可怕，因为命运和你这个作品是息息相关的。当你把作品拍完了的时候，它是给你打了个包，把这个放下，然后你再往前走。这像是对你自己内心的一个深入过程，认识自己，包括人性。人性是非常的复杂，我们到底能复杂到哪个程度或者黑暗到什么程度，在你拍片子过程中认识别人，也是认识自己。

<p><b>你看到这个人是什么样子，实际上你是自己的内心关照。</b>
<br>写小说的也有很多人是这样的，强烈的想象会影响到现实的嘛。我们拍片子拍到最后，就把自己放在这个位置上，心理肯定都会有感觉。一般心情都不会特别好，不像拍电影或搞当代艺术，幻想的成分会少得多，都非常现实，对人、对整个事情也不会报有特别大的幻想。

<p><b>那多悲观啊，这种生活。</b>
<br>在你认清你想要什么的情况之下，在意识到有个命在里面，然后再做一些事情的时候，不悲观。

<p><b>那你把自己置身到里面去了，把你的情感、生活牵扯到一起了啊。</b>
<br>没有做完之前都是这个样子的，做完之后，你就和它一点关系都没有了，你就过了这一关了。

