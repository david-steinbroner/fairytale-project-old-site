<b>受访者1。 &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;（&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;）：专栏作家，1970后,北京人</b>
<p><b>你去看了文献展吗？</b>
<br>我看不懂卡塞尔文献展，看不懂。但这并不重要吧，因为这些东西本来就不是让所有人都懂的。假设真的是谁来谁懂的话，那些作者肯定不高兴。至于德国嘛，给我的印象倒是蛮深刻的。古老、文明、发达，尤其是环境，满眼望去，全是绿色，一个普通郊区的风景都堪比九寨沟，真是让人叹为观止。看了以后终于明白人家为什么总说我们落后了！

<p><b>你怎么看待&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;的《童话》这个作品呢？</b>
<br>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;老这个作品想法大胆，有创新精神，我个人觉得比别人的那些玩意强多了！最起码，别人敢想也未必敢干。

<p><b>他的亭子坍塌了，你怎么看？</b>
<br>连万里长城都塌了不少，更何况一个普通的艺术作品。我觉得没必要把这件事拿出来说事儿。

<p><b>你怎么看艺术界里的“中国热”？</b>
<br>正常，中国毕竟是正在崛起的第三世界超级大国嘛!

<p><b>请谈谈你对《童话》的经历和体会。</b>
<br>就是去了趟国外，感觉跟在家不一样呗。说到了解，6天不可能有什么太多的了解，毕竟不同于长期生活。

<p><b>中国人与西方国家的人有什么共同点和不同点？</b>
<br>中国人与西方国家的人的婚姻观、价值观、世界观都存在很大差异，这是显而易见的。但细说到文化、历史和宗教，首先，一句两句也说不清楚，另外，就是咱还是不太了解，不敢妄自菲薄!

<p><b>能否谈谈你对文学的看法？</b>
<br>人，活在这个世界上，要承受生活、工作、家庭等多方面带来的压力。作为排解，有人选择了跳舞；有人选择了唱歌，有人选择了喝酒，有人选择了赌博。而我则是一个很有节制的人，我选择了我认为是更微妙的方法来自我放纵、自我排解－－比如文学。当然，也许那只是自命不凡而已，总之，这样效力更为持久，结果也不那么有害。我的的文章大多是寓教于乐，针讽时弊的。
<p>去年看过一个叫柯平的作家写过这么一段话：“想象着洋楼里面（西湖附近）的主人过的那种神仙般的生活，妻妾成群，童仆伺候，食有鱼，出有车，有时候确实让人感慨万千。问题是真实的社会从来就由富人与穷人共同组成，对此，你当然可以表示愤怒，但也可以保持沉默。如果让我选择，我想还是选择后者比较好一些。”这话就是典型的对社会、对读者不负责任，说句不客气的话，此人枉读了那么多书。如果世人都像他这般，哪儿来的鲁迅，哪儿又来的老舍！
<p>有人说我太过“愤青”。那怎么办？既然看见了不平之事，装聋作哑，我妈可没教过！还有人说我太过“搞笑”。在今天一个绝大多数人都苦哈哈挣命的年代，套用郭德钢的一句话：先搞笑吧，如果不搞笑那就太搞笑啦！
<p>亚里士多德说过：“心灵的高尚之处在于能公开说出自己的爱恨，能十分坦诚地评论各种事情，能为了真理不顾别人的赞成或反对。”我是不是可以这样理解，一个作家、一个时代的歌者如果不能反映现实，不能实话实说，那他就不是一个高尚的人，而成为一个高尚的人，难道不是所有的人应该追求的吗？

