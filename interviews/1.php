<b>Interview 1. &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; (&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;), columnist, born in 1970s, Beijing</b>

<p><b>Have you seen the Documenta Archive?</b>
<br>I don’t understand Documenta Kassel, I just don’t. But I think it doesn’t matter, those things aren't supposed to be understood by everyone in the first place. The artists won’t certainly wouldn't be happy if everyone and anyone could understand. As for Germany, it’s quite impressive. It's ancient, cultured, developed, and the environment - everywhere you see green. It simply astonishes me that here, a regular neighborhood's scenery is as beautiful as Jiuzhai Valley. No wonder they call us “undeveloped”!

<p><b>How do you feel about &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;’s Fairytale?</b>
<br>It’s audacious and creative, so much better than other people's junk. At least, even if other people thought it up, they wouldn't dare do it.

<p><b>How do you feel about the fact that "Template" collapsed?</b>
<br>Several places of the Great Wall also collapsed, an ordinary piece of art collapsing doesn't compare. I don't think it's that big a deal.

<p><b>What do you think of the art world's “China Fever”?</b>
<br>It's quite normal, China is rapidly rising third-world superpower!

<p><b>Let’s talk about your experience in Fairytale.</b>
<br>Being abroad is different from being at home. It’s impossible to learn much in just six days, after all, it's nothing like living here for a long time.

<p><b>What’s the difference between Chinese people and western people?</b>
<br>It goes without saying that Chinese people and western people have very different views on marriage, different sets of values and world views. As to the details about culture, history and religion, first, it can't be explained in just a few sentences, besides, I'm not feigning modesty when I say I really don't understand these things!

<p><b>Could you talk about your view on literature?</b>
<br>We live in this world bearing great pressure from life, work and family. Some people choose to dance for relaxation, others choose to sing, drink, or gamble. I am a moderate man and I choose a more delicate way to relax and indulge myself, and that is literature. Of course this may simply be my self-glorification, but this kind of relaxation is more lasting and less detrimental. Most of my articles are funny, educational and critical.

<p>Last year I read some words by a writer called Ke Ping, “Sometimes it makes you sigh to think of the wonderful lives in the Foreign Building (somewhere near West Lake): wives and concubines, obedient servants, delicious fish on the dinner table and fancy cars outside. The problem is, society is made up of the wealthy as well as the poor. You can choose anger, you can also choose silence. For me the latter is better”. I think such opinion is typically irresponsible. Honestly speaking this man has read so many books for vain. If everybody is like him, there would be no Lu Xun, and there would be no Lao She.

<p>Some might say I am too much a “Fenqing (angry young man).”* Well, my mother didn’t teach me to act like a blind man when I see something wrong. Others might say I am “too funny”, well in a world that everyone is struggling to survive, to quote Guo De Gang, “it’s too funny not to be funny”. Aristotle said: “The nobility of mind lies in its ability of speaking out its love and hate, commenting honestly and disregarding other people’s approval or disapproval for the sake of truth”. For me, if a writer can’t present us with reality and tell the truth, then he is not a noble one. Shouldn’t everyone try to be noble? 

<p>
*Translator's note: a colloquialism for "angry youth"
