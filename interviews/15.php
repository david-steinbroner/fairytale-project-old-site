<b>Interview 15. &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;, Company employee, female, born in 1960s, Xinjiang</b>

<p><b>Did you communicate with local people in Kassel? If so, What did you chat about?</b>
<br>I do not speak English, so had no direct communication with local residents. But I came across a German who spoke Chinese, and he liked China a lot, probably because he wanted to understand  Chinese culture. He was extremely friendly to us Chinese. After greeting us, he spoke to us for a very very long time. I felt especially surprised to meet a German here who spoke Chinese.  His Chinese was not fluent, sometimes with inappropriate grammar, and his expression was not very clear, but I feel that he had stayed in China, and liked communicating with Chinese people. He knew Fairytale, and asked us whether or not we participated. We said yes, and he felt that we were artists, which made me feel ashamed. They all regarded us as artists. Fairytale is a dream, to be abroad is a dream, and this opportunity makes the dream come to true.

<p><b>What do you think about Fairy Tale? Can you talk about it?</b>
<br>I think that &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; did it very successfully, because I found there that many people knew it, and understood it relatively. I followed him to visit the exhibition, a group of us, and many people surrounded him, asking for signatures, or taking pictures with him. I think that he created the activity, with such a large investment, and the fact that it was free to us, is incredible. I think it is a kind of great success.

<p><b>What impressions have the exhibited works left on you?</b>
<br>The foreign artist works, some are so profound, and I do not understand them. I am not working in the Arts. But I have carefully observed &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;'s 1001 chairs, and found no repetition of them. And the one that collapsed, it was a very special designation. I think the collapse might have to do with the weather. Moreover, maybe the project is not so perfect. But even with its collapse, still many people went to visit, to observe, and to watch the collapse. It was still receiving a lot of attention.

<p><b>What are your son's feelings?</b>
<br>He was very excited, said the environment was extremely great, and people particularly friendly.  A local senior, a volunteer, invited him and other people to be guests to his home. My son is very excited, and when he came back he told me that German people were very refined, especially their rhythm of life, and others particularly friendly. This trip to visit other countries, made him very proud. Because Xinjiang is relatively isolated, economic development relatively backward, Few people in my neighbourhood have such limited opportunity to go abroad. People admire us for this international tour. My son’s dad also applied, but he did not pass it.  Five of my family applied, and were provided with only two seats. What a pity.

<p><b>Do you have any faith?</b>
<br>Do you mean religious faith?  I do not have, neither is my family. I think that each religious faith is different.  Domestic faiths in China are something very humane, supposedly.

<p><b>What issues do you care about? Such as environment, politics or economy?</b>
<br>Environmental, I think I should be concerned about. As to news, people like us do not pay special attention. As to economy, it seems that we somewhat do not have contacts.

<p><b>If there is an opportunity that you can stay here, are you willing to stay?</b>
<br>I am used to my own place, and I feel it is more comfortable back home.

