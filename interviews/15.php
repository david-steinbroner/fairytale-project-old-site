<b>受访者15。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;：公司职员，女，1960后，新疆人</b>

<br><br><br><b>你跟卡塞尔人交流了吗？都聊些什么呢？</b>
<br>我不懂英语，与当地人没有直接交流。但我在那里碰到一个会说中文的德国人，他特别喜欢中国，可能想了解一些中国的文化。他对中国人特别友好，跟我们打完招呼又聊了好长好长时间。我觉得特别奇怪，在那儿碰到德国人说中国话。他的中国话不是特别流畅，有的语法什么的用得不恰当，表达得也不是特别地清晰，但我觉得他在中国呆过，喜欢跟中国人交谈。他知道《童话》，就问我们是不是，我们说是，他就觉得我们都是艺术家，我觉得挺惭愧的，他们都把我们当成艺术家了。《童话》是一个梦想，出国是一个梦想，这次圆了这个梦想。 

<br><br><br><b>你觉得《童话》怎么样？聊聊吧</b>
<br>我觉得&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;搞这个活动挺成功的，因为我在当地的时候发现很多人都知道，都比较了解这个事。我跟他出去看过展览，我们一行几个人，很多人围观他，让他签字啊合影啊。我觉得他搞的这个活动，投资这么大，又是免费的，真的是不可思议，我觉得搞得算是很成功吧。

<br><br><br><b>展览上的作品给你什么样的印象呢？</b>
<br>外国的艺术品，有些挺深奥的，看不太懂，我也不是搞艺术的。但是我仔细看 &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;的1001把椅子，觉得没有一个重样的，还有他坍塌掉的那个作品，设计都很独特。我觉得坍塌可能和那里的气候有关系，再一个，可能这个作品不是很完美吧。但是即使坍塌了，还是有很多人去照相，去观察，去看那个坍塌的样子，还是挺受关注的。

<br><br><br><b>你儿子是怎样的感受呢？</b>
<br>他很激动，说环境特别好，人特别友好。当地的一个志愿者老人邀请他和其他一些人到家里做客，他特别激动，回来对我说觉得德国人特别地优雅，生活特别有节奏，而且待人特别友好。这一趟出国，他觉得很自豪，因为新疆这里比较偏僻，经济发展比较落后，周围人有这样机会的不多，能出国，大家都很羡慕。孩子的爸爸他也报名了，但是被删掉了。我们一家报了五个人，就给了两个名额，感觉很遗憾。

<br><br><br><b>你有信仰吗？</b>
<br>信教是吧？我不信教，我家里也没有人信教。我觉得各个宗教的信仰是不同的，国内信的应该都是很人性化的一些东西。

<br><br><br><b>你平时都关注一些什么问题呢？比如说环境、政治、经济？</b>
<br>环境方面，我觉得我应该是关心的。新闻的话，一般像我们这些人不是很注意，像经济吧，好像我们都不怎么接触。

<br><br><br><b>如果有机会留在下来的话，你会愿意吗？</b>
<br>在自己的地方呆惯了，还是觉得回自己的家乡舒服一点。


