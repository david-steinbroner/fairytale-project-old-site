<b>Interview 18: &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;：artist, male, born in 1970s, Heilongjiang</b> 

<p><b>How do you like Kassel?</b>
<br>I like this city very much. It is my first time abroad. It is beautiful and spacious here with a harmonious atmosphere. Germany is same as what I was told before. It has the dignity of the old imperialist and has transited to a relatively civilized situation as I imagined. As for it's natural environment, it is as clean, regular and neat as expected. What I am concerned with most is whether I could accustom myself to Beijing when I go back.

<p><b>What role does art play in your life?</b>
<br>I am an artist but I have not devoted myself wholeheartedly to art because I am more fond of sport-related issues. Only 30 percent of my energy is distributed to the creation of music, poetry and Chinese painting.

<p><b>What differences are there between this exhibition and domestic art from your point of view?</b>
<br>I skimmed over the exhibition. The works here are more original. I am familiar with art works around Area 798 and I  think they copy too much. It looks like we are copying and pirating others all the time. This phenomenon might also exist in the West since artists keep learning from each other. But judging from the overall situation, I would like to say that works here have more originality.

<p><b>How do you understand art?</b>
<br>If we try to explain art now, taking Kassel Documenta as an example, art nowadays might be less aesthetic. It broke aesthetics and frame and became meaningless.

<p><b>Do you feel that Chinese artists are kind of nervous?</b>
<br>I do think so. We are more or less influenced by our education and parents to have an underlying formatting and dogmatic attitude towards outside world.

<p><b>Where does your fear and anxiety come from when you face the world?</b>
<br>It may originate from the truth that I could not do anything directly. On the contrary, I have to beat around the bush to follow a tricky rule.

<p><b>Have your personal values been achieved?</b>
<br>Basically yes. I have discovered my life style. It may appear to be selfish while it is my habit. I could make myself happy now. I used to be unhappy all the time.

<p><b>Do you have any difficulties in communicating with others?</b>
<br>Yes, because I am quite a strong character most of the time and I hurt others accidentally. I feel that it is difficult to make agreements with others in both method and style.

<p><b>What is the relationship between China and the West?</b>
<br>It is conflicting in essence. Some people may work on their integration but they have more conflicting components, which is present in ideology. What education we have received compared with what they received, what institution do we have compared with what they have what situation we face now compared with what they face and how we earn money compared with how they earn money, all of which lead to the difference in ideology.

<p><b>What do you think of love?</b>
<br>As something we lost. Love does not exist in China now. Everyone is filled with desire and profit. Love is a rather Westernized concept and China does not provide conditions for love such as environment. Everything in China does not supply us with love resources.

<p><b>I always believe love is only related to heart!</b>
<br>What is the heart related to? The heart is connected to everything you see, hear and feel, and your heart is dominated by them.

<p><b>Does it mean the more material you have, the more love you occupy?</b>
<br>I am not sure about it, completely not sure. Some people are strong and some are weak. The attitude one adopts towards an issue will largely influence the result.

<p><b>Do you still believe in love?</b>
<br>I do believe. Love is something you have to believe in, like faith. You do not even know what it is, but you have to believe in it, at least partly believe. 

<p><b>Do you have faith?</b>
<br>Half-faith, half doubt for things. 

