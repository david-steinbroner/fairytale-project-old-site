<b>受访者18。&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;：艺术家，男，1970后，黑龙江人</b> 

<p><b> 你怎么看卡塞尔这个城市？</b>
<br>很喜欢。这是我第一次出国。这里很美，而且空间挺大，气氛挺融洽的。我以前道听途说的德国和我现在看到的是一个样。有老牌帝国主义的尊严，从以前过渡到现在相对文明一点的程度，是我能够想像到的。至于他们的自然环境，我也能想像到，有图片，干净、秩序化、整洁。我最关心的是回到北京还能不能适应。

<p><b>艺术在你生活中的地位如何？</b>
<br>我是艺术家，但是我没有为艺术付出全部的精力，因为我更喜欢体育方面的一些事情，只有百分之三十是投入到音乐、诗歌还有国画创作方面。

<p><b>你看了这些展览，觉得和国内的艺术比有什么差距？</b>
<br>我走马观花地看了一遍，这里的更具原创性。我在国内对798那带很熟，感觉他们COPY比较多，似乎我们在无限制地COPY一些东西，抄袭一些东西。当然西方可能也有这样的，艺术家之间都在互相学习，但从大的环境来看，肯定这儿的原创性更强。

<p><b>你怎么理解艺术？</b>
<br>如果现在我们再去解释艺术，以卡塞尔的五年展为例，现在的艺术可能更加地不具有审美性，打碎审美的东西，打碎框架的东西，变得无意义，找不到它的任何意义⋯⋯

<p><b>你有没有觉得中国的艺术家有点紧张？</b>
<br>觉得。我们肯定或多或少地受了影响，从幼儿的教育和父母的影响，对待一些事物的态度存在教条化，潜在的格式化。

<p><b>你面对世界的时候，内心的焦虑和恐惧来自哪里？</b>
<br>来源就是做事情好像不能直接，不能直来直去，做什么事情都要拐弯抹角地，遵循一种狡猾的原则。

<p><b>你的个人价值是否已经实现了？</b>
<br>基本上实现了，因为我已经找到了我的生活方式。这可能显得有点自私，但是这就是我的习惯，我能让自己怎么快乐起来。以前经常不快乐。

<p><b>你和别人沟通有障碍么？</b>
<br>有，因为我多数的时候，似乎显得更有个性一点。还有，有意无意经常会伤害一些人。相处时间长了，遇到事情的时候，很难合拍，做事手法、方式，很难合拍。

<p><b>中国和西方之间的关系是什么样的？</b>
<br>本质上是抵触的，可能有一批人在想一些办法融合，但总体来讲还是抵触的成分比较多。这表现在意识形态上。我们从小受的是什么教育，他们受的是什么教育，他们的制度是什么，我们的制度是什么，他们的现状是怎么样，我们的现状什么样，他们挣钱什么样，我们挣钱什么样，这些都是导致意识形态差异的东西。

<p><b>你怎么看爱情？</b>
<br>缺失的东西。我们中国哪有爱情啊，大家都揣满了欲望和利益，很难有爱情吧！爱情是比较西化的东西，中国现在目前的状况不提供爱情的条件，比如环境，所有的一切都不提供爱情的资源。

<p><b>我一直以为爱情只跟心灵有关系呢！</b>
<br>心灵是跟什么有关系？心灵一定是和你看到的、听到的、感受到的一切有关系，你的心灵是受它们支配的。

<p><b>那不会是一个人物质越多，所占有的爱情就越多吧？</b>
<br>这个不能确定，完全不能确定。人，有的坚强，有的脆弱，他对待一件事情的态度所能达到的结果都不一样。

<p><b>那你还相信爱情么?</b>
<br>相信。这个东西是你必须相信的，像信仰一样，有点那种感觉。你都不知道是什么，但必须相信，至少是半信半疑吧。

<p><b>那你有信仰么？</b>
<br>半信半疑。对什么都一样。

